#!/usr/bin/env python3
"""Write c/tests/float/vectors.lua: float edge and pseudo-random vectors for
the ELF on Sail (c/tests/float/run_sail.sh). Each output line is

  x y  x+y x-y x*y x/y x%y x//y  x<y x<=y x==y  x|0

with floats as the signed 64-bit integer of their bits (string.pack), and
`x|0` the integer or `e` (luaV_tointegerns F2Ieq fails); then one line
`i i+0.0` per integer (`__floatdidf`). Lua/Num/F64Test.lean reads the run's
output (vectors.sail.out) and compares it with F64 and Lua.Num.Arith.
"""
import random, struct, os

def f2b(f):
    return struct.unpack('<Q', struct.pack('<d', f))[0]

POS = [0, 1, 2, 3, 0x000fffffffffffff, 0x0010000000000000, 0x0010000000000001,
       0x3fe0000000000000, 0x3ff0000000000000, 0x3ff0000000000001, 0x3ff8000000000000,
       0x4008000000000000, 0x4330000000000000, 0x4340000000000001, 0x43e0000000000000,
       0x7fefffffffffffff, 0x7ff0000000000000, 0x7ff8000000000000, 0x3fb999999999999a]
EDGES = POS + [b | (1 << 63) for b in POS]

rng = random.Random(20261006)
pairs = []
# a structured subset of edge pairs
for i, x in enumerate(EDGES):
    for j, y in enumerate(EDGES):
        if (i * 7 + j * 3) % 5 == 0:
            pairs.append((x, y))
# ties and near-ties for add: 2^53 + odd
for k in range(6):
    pairs.append((f2b(2.0 ** 53), f2b(float(2 * k + 1))))
# random finite pairs, same and nearby exponents, and full-range
for _ in range(60):
    x = rng.getrandbits(64)
    e = (x >> 52) & 0x7ff
    m = rng.getrandbits(52)
    y = ((x >> 63) ^ rng.getrandbits(1)) << 63 | (min(2046, max(0, e + rng.randint(-60, 60))) << 52) | m
    pairs.append((x, y))
for _ in range(20):
    pairs.append((rng.getrandbits(64), rng.getrandbits(64)))
# fmod with large exponent gaps, exact
for _ in range(20):
    x = f2b(rng.uniform(1, 2) * 2.0 ** rng.randint(-1000, 1000))
    y = f2b(rng.uniform(1, 2) * 2.0 ** rng.randint(-1000, 1000))
    pairs.append((x, y | (rng.getrandbits(1) << 63)))

ints = [0, 1, -1, 2 ** 53, 2 ** 53 + 1, 2 ** 53 + 3, -(2 ** 53) - 1, 2 ** 63 - 1, -(2 ** 63),
        2 ** 54 + 2, 2 ** 54 + 6, 123456789012345678] + [rng.getrandbits(64) - 2 ** 63 for _ in range(20)]

def lit(b):  # a Lua hex integer literal (wraps like the bits)
    return '0x%x' % b

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'vectors.lua')
with open(out, 'w') as f:
    f.write('-- GENERATED by c/tests/float/gen_vectors.py. Float vectors for the ELF on Sail.\n')
    f.write('local function B(x) return (string.unpack("<i8", string.pack("<d", x))) end\n')
    f.write('local function F(i) return (string.unpack("<d", string.pack("<i8", i))) end\n')
    f.write('local V = {\n')
    for x, y in pairs:
        f.write('  {%s, %s},\n' % (lit(x), lit(y)))
    f.write('}\n')
    f.write('for _, v in ipairs(V) do\n')
    f.write('  local x, y = F(v[1]), F(v[2])\n')
    f.write('  local ok, i = pcall(function() return x | 0 end)\n')
    f.write('  print(v[1], v[2], B(x + y), B(x - y), B(x * y), B(x / y), B(x % y), B(x // y),\n')
    f.write('        x < y, x <= y, x == y, ok and i or "e")\n')
    f.write('end\n')
    f.write('local I = {%s}\n' % ', '.join(lit(i % 2 ** 64) for i in ints))
    f.write('local z = F(0)\n')
    f.write('for _, i in ipairs(I) do print(i, B(i + z)) end\n')
print(out, len(pairs), 'pairs', len(ints), 'ints')
