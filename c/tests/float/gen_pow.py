#!/usr/bin/env python3
"""Vectors for the differential tests of `Lua/Num/Pow.lean` (`Lua.Num.numpow`,
the ELF's `x ^ y`: `luai_numpow` over newlib's fdlibm `pow`) against the ELF.

Writes, next to this file:
  pow.vec     one pair per line, `x y` as their 64 bits in hex;
  pow_*.lua   print the bits of `x ^ y` for each pair as a signed integer
              (`string.pack`), split to fit the ELF's 64 KiB chunk region;
  snan.vec, pow_snan.lua
              signalling-NaN operands, which `Float.Model` cannot hold
              (`ofBits` canonicalises them): reported for information.
The operands come from `string.unpack` at run time, so host `luac` cannot
constant-fold `^` (it would use glibc `pow`). `scripts/test_pow.lean` computes
the lines of `pow.vec`; `run_pow.sh` compares them with the ELF on Sail.
Deterministic (seeded).
"""
import os, random, struct

HERE = os.path.dirname(os.path.abspath(__file__))
rng = random.Random(20261006)
PER_FILE = 260

def bits(x): return struct.unpack('<Q', struct.pack('<d', x))[0]
def dbl(b): return struct.unpack('<d', struct.pack('<Q', b & (2**64 - 1)))[0]
def nxt(x, d=1): return dbl(bits(x) + d) if x >= 0 else dbl(bits(x) - d)

V = []
def add(x, y):
    V.append((x if isinstance(x, int) else bits(x), y if isinstance(y, int) else bits(y)))

NAN, NNAN, PNAN = 0x7ff8000000000000, 0xfff8000000000000, 0x7ff8000000000123
INF, NINF = bits(float('inf')), bits(float('-inf'))

# special operands crossed (e_pow.c's special-case ladder, w_pow.c's 0**0)
S = [0, 1 << 63, INF, NINF, NAN, NNAN, PNAN, bits(1.0), bits(-1.0), bits(0.5), bits(-0.5),
     bits(2.0), bits(-2.0), bits(3.0), bits(-3.0), bits(2.5), bits(-2.5), bits(1e300),
     bits(-1e300), bits(1e-300), 1, 0x800fffffffffffff, bits(nxt(1.0)), bits(nxt(1.0, -1)),
     bits(2.0**53), bits(-(2.0**53 + 2)), bits(2.0**64), bits(-(2.0**65)), bits(1.0/3)]
for x in S:
    for y in S:
        add(x, y)
# exact powers
for x in [2.0, 3.0, 5.0, 7.0, 10.0, -2.0, -3.0, 0.5, -0.5, 1.5, 0.1]:
    for y in [-10, -3, -1, 3, 4, 5, 7, 10, 15, 22, 31, 33]:
        add(x, float(y))
# y = 0.5 (sqrt path) and other halves
for x in [0.0, 2.0, 4.0, 1e-310, 1e308, 0.1, 3.0, 1e-300, -4.0, -0.0]:
    for y in [0.5, -0.5, 1.5, 0.25, -1.5]:
        add(x, y)
# y = 2 (luai_numpow's a*a) and y = +-1
for x in [3.0, -1.5, 1e200, 1e-200, 0.1]:
    for y in [2.0, 1.0, -1.0]:
        add(x, y)
# negative x with integral (odd, even, huge) and non-integral y
for _ in range(40):
    x = -(10 ** rng.uniform(-3, 3))
    y = rng.choice([float(rng.randint(-40, 40)), rng.uniform(-10, 10),
                    float(rng.randint(-40, 40)) + 0.5, 2.0 ** rng.randint(21, 60),
                    float(rng.randrange(1, 2**53) | 1)])
    add(x, y)
for y in [2.0**52 + 1, 2.0**52, 2.0**53, 2.0**52 + 0.5, 2.0**20 + 1, 2.0**21 + 1, 2.0**31 + 1,
          2.0**32 + 1, 1e20, -(2.0**52 + 1), 3.0, -3.0]:
    add(-1.0000001, y)
    add(-0.999, y)
    add(-1.0, y)
# overflow / underflow / subnormal results and the boundaries of e_pow.c:276-288
for k in range(-1080, -1018, 3):
    add(2.0, float(k)); add(2.0, k + 0.25); add(-2.0, float(k))
for y in [1023.0, 1023.5, 1023.9999999999999, 1024.0, nxt(1024.0, -1), nxt(1024.0),
          -1074.0, -1074.5, -1075.0, nxt(-1075.0, -1), nxt(-1075.0), -1076.0, 1025.0]:
    add(2.0, y); add(-2.0, y)
for y in [-307.0, -308.0, -310.0, -315.0, -320.0, -323.0, -324.0, 308.0, 309.0, 307.5]:
    add(10.0, y)
for x in [1e-200, 1e200, 0.5, 1.7976931348623157e308, 5e-324]:
    for y in [1.5, 2.5, -1.5, -2.5, 0.75]:
        add(x, y)
# |y| huge (e_pow.c:199-218): x close to 1, |y| > 2^31 and > 2^64
for x in [nxt(1.0), nxt(1.0, -1), 1 + 2.0**-25, 1 - 2.0**-25, 1 + 2.0**-21, 1.0001, 0.9999,
          -nxt(1.0), -(1 - 2.0**-30)]:
    for y in [2.0**31 + 2, 2.0**40, -(2.0**40), 2.0**60, 2.0**65, -(2.0**65), 1e300, 4.5e15]:
        add(x, y)
# random doubles
for _ in range(120):
    add(10 ** rng.uniform(-20, 20), rng.uniform(-30, 30))
for _ in range(60):
    add(rng.uniform(0, 4), rng.uniform(-200, 200))
for _ in range(40):
    add(rng.getrandbits(64), rng.getrandbits(64))
for _ in range(40):
    add(rng.getrandbits(63), bits(rng.uniform(-3, 3)))

SNAN = [(0x7ff0000000000001, 0), (0x7ff4000000000000, 1 << 63), (bits(1.0), 0x7ff0000000000001),
        (bits(1.0), 0xfff4000000000000), (0x7ff4000000000000, bits(3.0)),
        (bits(2.0), 0x7ff4000000000000), (bits(-1.0), 0x7ff4000000000000)]

HEAD = ('local function B(x) return (string.unpack("<i8", string.pack("<d", x))) end\n'
        'local function F(i) return (string.unpack("<d", string.pack("<i8", i))) end\n')

def lua(path, pairs, what):
    with open(path, 'w') as f:
        f.write('-- GENERATED by c/tests/float/gen_pow.py. %s\n' % what)
        f.write(HEAD + 'local V = {\n')
        for x, y in pairs:
            f.write('  {0x%x, 0x%x},\n' % (x, y))
        f.write('}\nfor _, v in ipairs(V) do print(B(F(v[1]) ^ F(v[2]))) end\n')

def vec(path, pairs):
    with open(path, 'w') as f:
        for x, y in pairs:
            f.write('%016x %016x\n' % (x, y))

for old in os.listdir(HERE):
    if old.startswith('pow_') and old.endswith('.lua'):
        os.remove(os.path.join(HERE, old))
vec(os.path.join(HERE, 'pow.vec'), V)
for i in range(0, len(V), PER_FILE):
    lua(os.path.join(HERE, 'pow_%d.lua' % (i // PER_FILE + 1)), V[i:i + PER_FILE],
        '`x ^ y` vectors %d..%d of pow.vec.' % (i + 1, min(len(V), i + PER_FILE)))
vec(os.path.join(HERE, 'snan.vec'), SNAN)
lua(os.path.join(HERE, 'pow_snan.lua'), SNAN, 'Signalling-NaN operands (information only).')
print('pow.vec: %d pairs in %d files; snan.vec: %d pairs' %
      (len(V), (len(V) + PER_FILE - 1) // PER_FILE, len(SNAN)))
