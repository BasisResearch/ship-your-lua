#!/usr/bin/env python3
"""Obligation census (abstraction-discovery step 1).

Lists every hand-written proof in files that are not verbatim copies
(experiments/port/copied.txt) and not generated (a `GENERATED by` header):
top-level theorems/lemmas and, inside them, per-case arms (`case X =>`,
`| .X ... =>` in term-mode matches, `·` bullets at the top tactic level are
not split). For each: file, name, proof lines, and the commit that
introduced the name (git log -S), ordered by that commit's time.

    python3 abstractions/census.py [--json out.json]
"""
import json, os, re, subprocess, sys
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
copied = set(open("experiments/port/copied.txt").read().split())

def lean_files():
    for d in ("Lua", "Vsa", "VsaIris", "tcb"):
        for dp, _, fs in os.walk(d):
            for f in fs:
                if f.endswith(".lean"):
                    p = os.path.join(dp, f)
                    if p in copied: continue
                    head = open(p, errors="ignore").read(400)
                    if "GENERATED" in head: continue
                    yield p

DECL = re.compile(r"^(?:@\[[^\]]*\]\s*)?(?:private\s+|protected\s+)?(theorem|lemma)\s+([^\s:({]+)")
TOP = re.compile(r"^(?:@\[|/--|/-!|theorem|lemma|def|abbrev|structure|inductive|instance|example|namespace|end|section|open|variable|set_option|mutual|noncomputable|private|protected|macro|syntax|#)")
CASE = re.compile(r"^\s+(?:case\s+(\w+)\s*=>|\|\s*@?\.?(\w+)\b.*=>)")

def decls(path):
    lines = open(path, errors="ignore").read().splitlines()
    out = []; i = 0
    while i < len(lines):
        m = DECL.match(lines[i])
        if m:
            j = i + 1
            while j < len(lines) and not TOP.match(lines[j]): j += 1
            body = [l for l in lines[i:j] if l.strip() and not l.strip().startswith("--")]
            spans = []
            for k in range(i, j):
                cm = CASE.match(lines[k])
                if cm:
                    ind = len(lines[k]) - len(lines[k].lstrip())
                    e = k + 1
                    while e < j and (not lines[e].strip() or len(lines[e]) - len(lines[e].lstrip()) > ind): e += 1
                    spans.append((k, e, cm.group(1) or cm.group(2)))
            cases = []
            for k, e, name in spans:
                # an arm's own cost excludes the arms nested inside it
                inner = set()
                for k2, e2, _ in spans:
                    if k < k2 and e2 <= e: inner.update(range(k2, e2))
                cases.append((name, sum(1 for x in range(k, e) if x not in inner and lines[x].strip())))
            out.append({"file": path, "name": m.group(2), "line": i + 1, "lines": len(body), "cases": cases})
            i = j
        else:
            i += 1
    return out

def intro_time(name, path):
    r = subprocess.run(["git", "log", "--reverse", "--format=%ct %h", "-S", name, "--", path],
                       capture_output=True, text=True).stdout.split()
    return (int(r[0]), r[1]) if r else (0, "uncommitted")

def main():
    rows = []
    for p in lean_files():
        for d in decls(p):
            d["t"], d["commit"] = intro_time(d["name"], p)
            rows.append(d)
    rows.sort(key=lambda d: d["t"])
    if "--json" in sys.argv:
        json.dump(rows, open(sys.argv[sys.argv.index("--json") + 1], "w"), indent=1)
    by = defaultdict(list)
    for d in rows: by[d["file"]].append(d)
    for f, ds in sorted(by.items()):
        print(f"{f}: {len(ds)} theorems, {sum(d['lines'] for d in ds)} lines, "
              f"{sum(len(d['cases']) for d in ds)} case arms")


if __name__ == "__main__":
    main()
