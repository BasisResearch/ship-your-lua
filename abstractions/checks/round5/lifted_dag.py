#!/usr/bin/env python3
"""Round 5 census, level (b): the shape of each soft-float routine's lifted
function `F` (`Lua/Vm/Fn/<R>.lean`, `<R>/Defs.lean`, generated by
`scripts/gen_lua_fn.py`), read off the generated Lean text.

Per routine:
* `nodes`: value nodes `N_<pc>`; `paths`: root-to-leaf paths of `F`'s DAG
  (each `if` doubles, each tail call follows); a proof of `F = S` by case
  analysis on the routine's own branches has this many leaves;
* `vshift`: shifts by a non-literal amount (`shift_bits_* x (extractLsb v …)`
  with `v` not a literal: nonlinear for `omega`);
* `mem`: reads of the routine's own stack frame (`bytesT8 m (sp …)`): spills
  reloaded, which a proof must forward through the frame's stores first;
* `clz`: calls of `clz64` (`__clzdi2`, the normalisation count).

Then the **stage law** check: node bodies alpha-normalised (variable names
`v<k>` and node names `N_<pc>` replaced by position), grouped across
routines. A body that occurs in several routines is a candidate shared
stage (`_FP_PACK_*`, `_FP_ROUND`, `_FP_UNPACK_*`): the law says the lifted
functions factor through the same stage functions.

    python3 abstractions/checks/round5/lifted_dag.py > abstractions/checks/round5/lifted_dag.out
"""
import re
import sys
from collections import defaultdict
from functools import lru_cache
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
FN = ROOT / "Lua/Vm/Fn"
ROUTINES = {"Floatsidf": ["Floatsidf.lean"], "Floatdidf": ["Floatdidf.lean"],
            "Fixdfdi": ["Fixdfdi.lean"], "Eqdf2": ["Eqdf2.lean"], "Ledf2": ["Ledf2.lean"],
            "Gedf2": ["Gedf2.lean"], "Adddf3": ["Adddf3/Defs.lean"], "Subdf3": ["Subdf3/Defs.lean"]}

DEF = re.compile(r"^def (N_[0-9a-f]+|F) *(?:\(m : Mem\) \(s : Nat\) \(r : BitVec 64\))? *(?:\(([v0-9 ]+) : BitVec 64\))? *: BitVec 64 :=\n(.*?)(?=\n\n|\ndef |\ntheorem )", re.S | re.M)


def parse(text):
    out = {}
    for m in DEF.finditer(text):
        name, params, body = m.group(1), (m.group(2) or "").split(), m.group(3)
        out[name] = (params, body)
    return out


def calls(body):
    return re.findall(r"\b(N_[0-9a-f]+)\b", body)


def norm(params, body):
    b = body
    for i, p in enumerate(params):
        b = re.sub(rf"\b{p}\b", f"P{i}", b)
    b = re.sub(r"\bN_[0-9a-f]+\b", "N", b)
    return re.sub(r"\s+", " ", b).strip()


def main():
    groups = defaultdict(list)
    print("routine\tnodes\tifs\tpaths\tvshift\tmem\tclz\tpack_refs")
    for r, files in ROUTINES.items():
        text = "".join((FN / f).read_text() for f in files)
        defs = parse(text)

        @lru_cache(None)
        def npaths(n):
            params, body = defs[n]
            if body.lstrip().startswith("if "):
                th, el = body.split("\n  else\n", 1)
                a = calls(th.split("then", 1)[1])
                b = calls(el)
                return (npaths(a[0]) if a else 1) + (npaths(b[0]) if b else 1)
            cs = calls(body)
            # a straight node tail-calls at most one node (its successor);
            # inner calls are value arguments, one path each
            return npaths(cs[0]) if cs else 1
        ifs = sum(1 for p, b in defs.values() if b.lstrip().startswith("if "))
        vshift = len(re.findall(r"shift_bits_(?:left|right|right_arith) .*?\(Sail\.BitVec\.extractLsb (?!\(0x)", text))
        mem = len(re.findall(r"bytesT8 \(m\)", text)) // 1
        clz = text.count("clz64")
        # the pack node: (e <<< 52) ||| f ||| (s <<< 63)
        pack = [n for n, (p, b) in defs.items()
                if "(0x34#6)" in b and "(0x3f#6)" in b and "|||" in b and not b.lstrip().startswith("if ")
                and "shift_bits_left" in b and len(b) < 400]
        prefs = sum(len(re.findall(rf"\b{n}\b", text)) for n in pack)
        print(f"{r}\t{len(defs) - 1}\t{ifs}\t{npaths('F')}\t{vshift}\t{mem}\t{clz}\t{prefs} ({','.join(pack)})")
        for n, (p, b) in defs.items():
            if n != "F":
                groups[norm(p, b)].append(f"{r}.{n}")
    print()
    print("shared node bodies (alpha-normalised) across routines:")
    shared = [(k, v) for k, v in groups.items() if len({x.split('.')[0] for x in v}) > 1]
    shared.sort(key=lambda kv: -len(kv[1]))
    for k, v in shared:
        print(f"  {len(v)} occurrences in {sorted({x.split('.')[0] for x in v})}: {k[:160]}")
    print(f"total distinct bodies {len(groups)}; shared across routines {len(shared)}")


if __name__ == "__main__":
    main()
