class Fn:
    def __init__(self, fn):
        self.fn = fn
        CUR_FN[0] = fn
        self.mod, self.entry, self.F, self.args = ROUTINES[fn]
        self.W = WINDOW.get(fn, self.F)
        lo, hi = next((a, b) for f, _, a, b, *_ in gla.HELPERS if f == fn)
        gla_lo[0], gla_lo[1] = lo, hi
        self.segs = [Seg(n, a, b, s) for n, a, b, s in gla.helper_specs(fn)]
        # lane float-sf4: a `jr` through a jump table is a node with one
        # polarity per entry (`k`), each a jump to the entry's target
        self.jt, segs = {}, []
        for s in self.segs:
            jt = JUMPS.get(fn, {}).get(s.hi - 4)
            if not jt:
                segs.append(s)
                continue
            self.jt[s.lo] = jt
            for k, t in enumerate(jt_targets(jt[0], jt[1])):
                c = copy.copy(s)
                c.kind, c.succ, c.k = "goto", t, k
                if not (gla_lo[0] <= t < gla_lo[1]):
                    raise SystemExit(f"{s.name}: table entry {k} jumps out of the helper")
                segs.append(c)
        self.segs = segs
        # lane float-sf6: in a routine with an outer store, a frame slot read
        # after the store (`with_errno`'s `s0` restore after `errno`'s `sw`)
        # reads the memory before it (`bytesT8_wm4_far`, the outer word apart)
        if fn in OUTER:
            for s in self.segs:
                s.wm4_reads = False
                for r, e in list(s.post.items()):
                    e2 = strip_wm4(e)
                    if e2 != e:
                        s.post[r], s.wm4_reads = e2, True
        # a framed callee's patch: `.rodata` and the saved `ra` read through it
        self.patch = any(s.kind == "call" and s_callee(s).frame for s in self.segs)
        # the syntactic closers (`Kit/FnCall.lean`) where a callee's patch or a
        # forwarded slot's fact is in scope (`assumption` would unify slot
        # addresses by `whnf`)
        self.rod, self.ra_t = (("fn_rod_patch", "fn_ra_patch") if self.patch or fn in FORWARD
                               else ("fn_rod", "fn_ra"))
        if fn in OUTER:
            self.rod, self.ra_t = "fn_rod_patch4", "fn_ra_patch4"
        self.facts = FACTS.get(fn, [])
        self.nodes = {}
        for s in self.segs:
            self.nodes.setdefault(s.lo, []).append(s)
        # the frame state of every node (0: before the prologue, F: inside the frame)
        self.off, self.ra = {self.entry: 0}, None
        work = [self.entry]
        while work:
            pc = work.pop()
            for s in self.nodes[pc]:
                if s.kind in TERM:
                    continue
                o = self.off[pc] - s.sp_delta
                if s.sp_delta:
                    if not self.F or s.sp_delta != -self.F:
                        raise SystemExit(f"{s.name}: frame {s.sp_delta}")
                    self.pro_imm = s.sp_imm
                    for a, d in wm8_chain(s.mem):
                        if d == "sdData_val v1":
                            self.ra = a
                    if self.ra is None:
                        raise SystemExit(f"{s.name}: the prologue does not save ra")
                if s.succ in self.off and self.off[s.succ] != o:
                    raise SystemExit(f"0x{s.succ:x}: frame {self.off[s.succ]} and {o}")
                if s.succ not in self.off:
                    self.off[s.succ] = o
                    work.append(s.succ)
        # topological order: successors first; a cycle's nodes (a strongly
        # connected component, Tarjan's order: post-order on a DAG) contiguous
        self.order, self.scc = [], {}
        self.tarjan()
        # lane float-sf5: the nodes on a cycle take fuel (`Kit/FnLoop.lean`);
        # a node that reaches one takes the termination fact `hT`
        self.cyc = {pc for pc in self.order
                    if len(self.scc_nodes(pc)) > 1
                    or any(s.kind not in TERM and s.succ == pc for s in self.nodes[pc])}
        if self.entry in self.cyc:
            raise SystemExit(f"{fn}: the entry is on a cycle")
        self.need_t = {}
        for pc in self.order:
            self.need_t[pc] = pc in self.cyc or any(
                (s.kind not in TERM and self.need_t.get(s.succ, s.succ in self.cyc)) or self.side(s)
                for s in self.nodes[pc])
        # the named premises its callees need (`Callee.premise`)
        self.prem = []
        for s in self.segs:
            if s.kind == "call" and s_callee(s).premise and s_callee(s).premise not in self.prem:
                self.prem.append(s_callee(s).premise)
        self.noncomp = any(s.kind == "call" and s_callee(s).noncomp for s in self.segs)
        self.fwd = fn in FORWARD
        # the saved `ra`'s slot (`hra`), never a forwarded slot
        self.ra_off = re.findall(r"\((0x[0-9a-f]+)#12\)", self.ra)[-1] if self.ra else None
        self.slots_in = {pc: [] for pc in self.order}
        self.need_m = {pc: True for pc in self.order}
        self.saves()
        # the memory functions take the caller's frame: they store it (`saves`)
        # or a callee's frame stores it (`{g}` in `Callee.mf`)
        self.mem_g = bool(self.sv_slot) or any(
            s.kind in ("call", "tail") and "{g}" in (s_callee(s).mf or "") for s in self.segs)
        # lane F1-F7: a register a node's only edge in sets to a literal is
        # that literal in the node (`OUTER`: `__errno`'s result, the address
        # of the outer store)
        self.val_g = False
        self.consts = {}
        if fn in OUTER:
            self.const_prop()
        if self.fwd:
            self.forward()
        elif fn in MEMLESS:
            self.mem_need()
        # lane float-sf6: a value function whose memory argument holds the
        # caller's saved registers (stored before a call whose callee reads
        # memory) takes the caller's frame `g`, as every node reading memory does
        self.val_g = self.mem_g and any(
            re.search(r"(?<![\w.])g\b", self.body(pc, s)) for pc in self.order for s in self.nodes[pc])

    def const_prop(self):
        """`self.consts`: node -> {register: literal} (an acyclic routine)."""
        preds = self.preds()
        closed = re.compile(r"\bv\d+\b|\bm\b|\bg\.|\bs\b|\br\b|\bvs[0-9a-f]+\b|\bfuel\b|\bk\b")
        for pc in reversed(self.order):          # the entry first
            ins = preds.get(pc, [])
            if pc == self.entry or len(ins) != 1 or pc in self.cyc:
                continue
            p, s = ins[0]
            post = self.edge_post(p, s)[0]
            cs = {r: post[r] for r in self.live(pc) if r in post and not closed.search(post[r])}
            if cs:
                self.consts[pc] = cs

    def edge_post(self, pc, s):
        """The registers and memory after segment `s` of node `pc` (a call's
        result and kept registers)."""
        post = {r: self.subst(pc, e) for r, e in s.post.items()}
        mem = self.subst(pc, s.mem)
        if s.kind == "call":
            fmt = self.call_fmt(pc, s, post, mem)
            post = {10: s_callee(s).val.format(**fmt),
                    **{r: post[r] for r in s_callee(s).keeps if r in post},
                    **{r: post[r] for r in FRAME if r in post},
                    **{r: v.format(**fmt) for r, v in s_callee(s).clobbers.items()}}
            if s_callee(s).frame:
                c = s_callee(s)
                mem = (f"memPatch ({mem}) ({c.mf.format(**fmt)}) ({fmt['sp']} - {c.frame}) "
                       f"{c.frame}")
        return post, mem

    def side(self, s):
        """Segment `s`'s side conditions that are conjuncts of `T` (`SIDE`)."""
        if s.name not in SIDE.get(self.fn, ()):
            return []
        return [(h, t) for h, t in s.hyps if re.match(r"h(lo|hi|ht|win|al)_", h)]

    def tarjan(self):
        """`self.order` (successors first, each cycle contiguous) and
        `self.scc` (node -> its component's id), by Tarjan's algorithm, the
        successors visited in segment order (so a DAG's order is the DFS
        post-order)."""
        index, low, stack, on = {}, {}, [], set()

        def visit(pc):
            index[pc] = low[pc] = len(index)
            stack.append(pc)
            on.add(pc)
            for s in self.nodes[pc]:
                if s.kind in TERM:
                    continue
                q = s.succ
                if q not in index:
                    visit(q)
                    low[pc] = min(low[pc], low[q])
                elif q in on:
                    low[pc] = min(low[pc], index[q])
            if low[pc] == index[pc]:
                comp = []
                while True:
                    q = stack.pop()
                    on.discard(q)
                    comp.append(q)
                    if q == pc:
                        break
                for q in reversed(comp):
                    self.scc[q] = pc
                    self.order.append(q)
        visit(self.entry)

    def scc_nodes(self, pc):
        return [q for q in self.order if self.scc[q] == self.scc[pc]]

    def same(self, pc, q):
        """`q` on the same cycle as `pc` (an edge inside it consumes fuel)."""
        return pc in self.cyc and q in self.cyc and self.scc[pc] == self.scc[q]

    def mem_need(self):
        """Which value functions read memory (the entry keeps `m`):
        `forward`'s last step, without forwarding, as a least fixpoint (a
        cycle's nodes pass `m` to each other only if one of them reads it)."""
        self.need_m = {pc: pc == self.entry for pc in self.order}
        changed = True
        while changed:
            changed = False
            for pc in self.order:
                if self.need_m[pc]:
                    continue
                for s in self.nodes[pc]:
                    if (re.search(MEM_RE, self.body(pc, s))
                            or (s.guard and re.search(MEM_RE, self.subst(pc, s.guard[0])))):
                        self.need_m[pc] = changed = True
                        break

    # ----------------------------------------------------------------------
    def preds(self):
        out = {pc: [] for pc in self.order}
        for pc in self.order:
            for s in self.nodes[pc]:
                if s.kind not in TERM:
                    out[s.succ].append((pc, s))
        return out

    def saves(self):
        """Lane float-sf4: callee-saved registers saved to their slots and
        reassigned mid-body (`__divdf3`'s `udiv_qrnnd` keeps the divisor's
        halves and the quotient in `s0`-`s3`). Per node: the registers that
        hold a value of the routine's (`spilled`, live registers of the node),
        and the save slots whose fact `hsv<off> : bytesT8 m slot = g.<s>` the
        node carries (`sv_in`: stored on every path in, restored after); a
        restore `ld s<i>, off(sp)` is the caller's value (`fn_sv_ld`)."""
        preds = self.preds()
        self.sv_slot, self.spilled, av_in, out = {}, {}, {}, {}
        self.sp_after = {}
        # a fixpoint: a cycle's back edges (lane float-sf5) join on a later
        # pass; without cycles the second pass repeats the first
        while True:
            prev = (dict(self.spilled), dict(av_in))
            for pc in reversed(self.order):          # the entry first
                if pc == self.entry:
                    sp, av = frozenset(), frozenset()
                else:
                    outs = [out[(p, id(s))] for p, s in preds[pc] if (p, id(s)) in out]
                    if not outs:                 # every edge in still to come
                        continue
                    if len({o[0] for o in outs}) != 1:
                        raise SystemExit(f"0x{pc:x}: callee-saved registers spilled on some paths only")
                    sp, av = outs[0][0], frozenset.intersection(*[o[1] for o in outs])
                self.spilled[pc], av_in[pc] = sp, av
                for s in self.nodes[pc]:
                    if s.kind in TERM:
                        # lane F1-F7: the epilogue's restores (`fmod`'s `ld s0, 16(sp)`)
                        left = {r for r in sp
                                if not ((m := re.fullmatch(SV_RE, s.post.get(r, f"v{r}")))
                                        and self.sv_slot.get(m.group(1)) == r and m.group(1) in av)}
                        if left:
                            raise SystemExit(f"{s.name}: returns with {sorted(left)} not restored")
                        continue
                    av2 = set(av)
                    pro = bool(s.sp_delta) and self.fn in PRO_SAVES
                    if s.mem != "m0" and ((self.inside(pc) and not s.sp_delta) or pro):
                        for a, d in wm8_chain(s.mem):
                            m = re.fullmatch(PRO_SLOT_RE if pro else SLOT_RE, a)
                            if not m:
                                continue
                            o, dm = m.group(1), re.fullmatch(r"sdData_val v(\d+)", d)
                            if dm and int(dm.group(1)) in FRAME and int(dm.group(1)) not in sp:
                                r = int(dm.group(1))
                                if self.sv_slot.setdefault(o, r) != r:
                                    raise SystemExit(f"{s.name}: save slot {o} of two registers")
                                av2.add(o)
                            elif o in self.sv_slot:
                                raise SystemExit(f"{s.name}: save slot {o} overwritten")
                    sp2 = set(sp)
                    for r in FRAME:
                        e = s.post.get(r, f"v{r}")
                        if e == f"v{r}":
                            continue
                        m = re.fullmatch(SV_RE, e)
                        if m and self.sv_slot.get(m.group(1)) == r and m.group(1) in av:
                            sp2.discard(r)
                        elif any(self.sv_slot.get(o) == r for o in av2):
                            sp2.add(r)
                        else:
                            raise SystemExit(f"{s.name}: x{r} reassigned before it is saved")
                    out[(pc, id(s))] = (frozenset(sp2), frozenset(av2))
                    self.sp_after[(pc, id(s))] = frozenset(sp2)
            if (self.spilled, av_in) == prev:
                break
        live, changed = {}, True
        while changed:                           # a fixpoint over the cycles
            changed = False
            for pc in self.order:                # successors first
                ls = set()
                for s in self.nodes[pc]:
                    ls |= set(re.findall(SV_RE, " ".join(s.post.values()))) & set(self.sv_slot)
                    if s.kind not in TERM:
                        ls |= live.get(s.succ, set())
                if live.get(pc) != ls:
                    live[pc], changed = ls, True
        self.sv_in = {pc: sorted(av_in[pc] & live[pc]) for pc in self.order}

    def seg_stores(self, pc, s):
        """The spill slots segment `s` of node `pc` stores: offset -> datum."""
        if not self.fwd or not self.inside(pc) or s.sp_delta:
            return {}
        out = {}
        if s.mem != "m0":
            for a, d in wm8_chain(s.mem):
                m = re.fullmatch(SLOT_RE, a)
                if m and d != "sdData_val v1" and m.group(1) not in self.sv_slot:
                    out[m.group(1)] = d
        return out

    def seg_loads(self, pc, s):
        """The spill slots segment `s` reads (in its post-state and guard)."""
        if not self.fwd or not self.inside(pc):
            return set()
        text = " ".join(list(s.post.values()) + [s.mem] + ([s.guard[0]] if s.guard else []))
        return set(re.findall(LOAD_RE, text)) - {self.ra_off} - set(self.sv_slot)

    def forward(self):
        """The slots available at every node (stored on every path into it)
        and live there (read by it or after it), and which lifted functions
        read memory."""
        preds = {pc: [] for pc in self.order}
        for pc in self.order:
            for s in self.nodes[pc]:
                if s.kind not in TERM:
                    preds[s.succ].append((pc, s))
        # lane float-sf6: fixpoints, so that they run on cyclic graphs (a
        # predecessor still to come is skipped: the greatest fixpoint of
        # `avail`, the least of `live`); on a DAG the first pass is the result
        avail, changed = {}, True
        while changed:
            changed = False
            for pc in reversed(self.order):      # the entry first
                if pc == self.entry:
                    new = set()
                else:
                    sets = [avail[p] | set(self.seg_stores(p, s)) for p, s in preds[pc] if p in avail]
                    new = set.intersection(*sets) if sets else set()
                if avail.get(pc) != new:
                    avail[pc], changed = new, True
        live, changed = {}, True
        while changed:
            changed = False
            for pc in self.order:                # successors first
                ls = set()
                for s in self.nodes[pc]:
                    after = (set() if s.kind in TERM
                             else live.get(s.succ, set()) - set(self.seg_stores(pc, s)))
                    ls |= self.seg_loads(pc, s) | after
                if live.get(pc) != ls:
                    live[pc], changed = ls, True
        for pc in self.order:
            self.slots_in[pc] = sorted(avail[pc] & live[pc])
            for s in self.nodes[pc]:
                bad = self.seg_loads(pc, s) - avail[pc]
                if bad:
                    raise SystemExit(f"{s.name}: reloads {sorted(bad)} not stored on every path")
        if self.cyc:                             # lane float-sf6: a least fixpoint over the cycles
            self.mem_need()
            return
        # which value functions read memory (successors first); the entry keeps `m`
        for pc in self.order:
            need = pc == self.entry
            for s in self.nodes[pc]:
                if re.search(MEM_RE, self.body(pc, s)):
                    need = True
                if s.guard and re.search(MEM_RE, self.subst(pc, s.guard[0])):
                    need = True
            self.need_m[pc] = need

    # ----------------------------------------------------------------------
    def dn(self, pc):
        """The lifted function of node `pc` (`F` at the entry)."""
        return "F" if pc == self.entry else f"N_{pc:08x}"

    def mn(self, pc):
        """A framed helper's memory function of node `pc` (`Fm` at the entry)."""
        return "Fm" if pc == self.entry else f"Nm_{pc:08x}"

    def ln(self, pc):
        """The lemma of node `pc` (`sum` at the entry)."""
        return "sum" if pc == self.entry else f"n_{pc:08x}"

    def tn(self, pc):
        """The termination function of node `pc` (`T` at the entry)."""
        return "T" if pc == self.entry else f"T_{pc:08x}"

    def fuel_arg(self, pc, q):
        """The fuel node `pc` passes its successor `q`: one less inside a
        cycle (`k`, under `pc`'s `match fuel`), `fnFuel` entering one."""
        if q not in self.cyc:
            return None
        return "k" if self.same(pc, q) else "Lua.Vm.Sim.fnFuel"

    def prem_binders(self):
        return "".join(f"({h} : {t}) " for h, t in self.prem)

    def prem_args(self):
        return "".join(f"{h} " for h, _ in self.prem)

    def framed(self):
        # lane float-sf6: by the window (a frameless routine that tail-calls a
        # framed callee patches the callee's window)
        return self.W > 0

    def inside(self, pc):
        return self.off[pc] != 0

    def regs(self, pc):
        """The registers pinned at node `pc` (the union of its polarities')."""
        rs = []
        for s in self.nodes[pc]:
            for r in s.pre:
                if r not in rs:
                    rs.append(r)
        return rs

    def live(self, pc):
        """The node's registers that are its lifted function's arguments."""
        return sorted(r for r in self.regs(pc)
                      if (r not in FRAME or r in self.spilled.get(pc, ())) and r not in (1, 2)
                      and r not in self.consts.get(pc, {}))

    def sp(self, pc):
        if not self.framed():
            return "f.sp"
        if self.inside(pc):
            return f"(BitVec.ofNat 64 s + sign_extend (m := 64) ({self.pro_imm}#12))"
        return "(BitVec.ofNat 64 s)"

    def val(self, pc, r):
        """The node's expression for register `r`."""
        if r in self.consts.get(pc, {}):
            return f"({self.consts[pc][r]})"
        if r == 2:
            return self.sp(pc)
        if r == 1:
            return "v1" if self.framed() and self.inside(pc) else "r"
        if r in FRAME and r not in self.spilled.get(pc, ()):
            return f"{'g' if self.framed() else 'f'}.{FRAME[r]}"
        return f"v{r}"

    def subst(self, pc, text):
        if self.sv_slot and self.inside(pc):     # a restore: the caller's value
            text = re.sub(SV_RE, lambda m: (f"g.{FRAME[self.sv_slot[m.group(1)]]}" if m.group(1) in self.sv_slot
                                            else m.group(0)), text)
        if self.fwd and self.inside(pc):
            text = re.sub(LOAD_RE, lambda m: (m.group(0) if m.group(1) == self.ra_off
                                              else f"vs{m.group(1)[2:]}"), text)
        text = re.sub(r"\bv(\d+)\b", lambda m: self.val(pc, int(m.group(1))), text)
        return re.sub(r"\bm0\b", "m", text)

    def slot_addr(self, pc, o):
        """The address of slot `o` inside the frame."""
        return f"(({self.sp(pc)} + sign_extend (m := 64) ({o}#12)).toNat)"

    def nargs(self, pc, memfn=False):
        """The lifted function's parameters (as binders)."""
        vs = " ".join([f"v{r}" for r in self.live(pc)] + [f"vs{o[2:]}" for o in self.slots_in[pc]])
        bv = f" ({vs} : BitVec 64)" if vs else ""
        fb = "(fuel : Nat) " if pc in self.cyc else ""
        if self.framed():
            mb = "(m : Mem) " if memfn or self.need_m[pc] else ""
            # a memory function stores the caller's callee-saved registers
            # to their save slots (`saves`)
            gb = " (g : SFrame)" if self.takes_g(pc, memfn) else ""
            return f"{fb}{mb}(s : Nat) (r : BitVec 64){gb}{bv}"
        if self.fn in LEAF_MF:
            return (fb + "(m : Mem) (f : HFrame)" + bv).strip()
        return (fb + bv.strip()).strip()

    def takes_g(self, pc, memfn):
        """Node `pc`'s memory function (or, under `val_g`, its value and
        termination functions when they read memory) takes `g`."""
        return self.mem_g if memfn else (self.val_g and self.need_m[pc])

    def napp(self, pc, mem="m", vals=None, memfn=False, slots=None, fuel=None, tfn=False):
        """Node `pc`'s lifted function (its memory function `memfn`, its
        termination function `tfn`) applied; `fuel` on a cycle."""
        vals = vals if vals is not None else {r: f"v{r}" for r in self.live(pc)}
        slots = slots if slots is not None else {o: f"vs{o[2:]}" for o in self.slots_in[pc]}
        args = [vals[r] for r in self.live(pc)] + [slots[o] for o in self.slots_in[pc]]
        a = " ".join(f"({x})" if not re.fullmatch(r"v\d+|vs[0-9a-f]+", x) else x for x in args)
        fa = f"{fuel} " if pc in self.cyc else ""
        if pc in self.cyc and fuel is None:
            raise SystemExit(f"0x{pc:x}: a cycle's node applied without fuel")
        if self.framed():
            f = self.mn(pc) if memfn else self.tn(pc) if tfn else self.dn(pc)
            mm = f"({mem}) " if memfn or self.need_m[pc] else ""
            gg = "g " if self.takes_g(pc, memfn) else ""
            return f"{f} {fa}{mm}s r {gg}{a}".rstrip()
        if self.fn in LEAF_MF:
            return f"{self.tn(pc) if tfn else self.dn(pc)} {fa}({mem}) f {a}".rstrip()
        return f"{self.tn(pc) if tfn else self.dn(pc)} {fa}{a}".rstrip()

    def pins(self, pc):
        """The node lemma's pin list."""
        out = [f"⟨Register.x{r}, v{r}⟩" for r in self.live(pc)]
        out += [f"⟨Register.x{r}, ({e})⟩" for r, e in self.consts.get(pc, {}).items()]
        if 1 in self.regs(pc):
            out.append(f"⟨Register.x1, {self.val(pc, 1)}⟩")
        if self.framed():
            out.append(f"⟨Register.x2, {self.sp(pc)}⟩")
            out += [f"⟨Register.x{r}, g.{f}⟩" for r, f in FRAME.items() if r not in self.spilled[pc]]
            return "[" + ", ".join(out) + "]"
        return "(" + " :: ".join(out + ["f.pins"]) + ")"

    def post(self, pc):
        fu = "fuel" if pc in self.cyc else None
        app = self.napp(pc, fuel=fu)
        if self.framed():
            pins = [f"⟨Register.x10, {app}⟩", "⟨Register.x2, BitVec.ofNat 64 s⟩"]
            pins += [f"⟨Register.x{r}, g.{f}⟩" for r, f in FRAME.items()]
            mem = f"memPatch m ({self.napp(pc, memfn=True, fuel=fu)}) (s - {self.W}) {self.W}"
            if self.fn in OUTER:
                A, n = OUTER[self.fn]
                mem = f"memPatch ({mem}) ({self.napp(pc, memfn=True, fuel=fu)}) {A} {n}"
            return f"SegSt r [{', '.join(pins)}] (ArmPay ({mem}) o)"
        return f"SegSt r (⟨Register.x10, {app}⟩ :: f.pins) (ArmPay m o)"

    # ----------------------------------------------------------------------
    def body(self, pc, s, memfn=False, tfn=False, sided=True):
        """The lifted function's value (or memory, or termination) along
        polarity `s` of node `pc`."""
        if tfn and sided and self.side(s):
            base = self.body(pc, s, False, True, False)
            return "(" + " && ".join([base] + [f"decide ({self.subst(pc, t)})"
                                               for _, t in self.side(s)]) + ")"
        if tfn and (s.kind in TERM or not self.need_t[s.succ]):
            return "true"
        if s.kind == "tail":
            return self.tail_body(pc, s, memfn)
        if s.kind == "ret":
            if memfn:
                return self.subst(pc, s.mem)
            return self.subst(pc, s.post[10])
        post, mem = self.edge_post(pc, s)
        vals = {}
        for r in self.live(s.succ):
            if r not in post:
                raise SystemExit(f"{s.name}: x{r} live at 0x{s.succ:x} but not carried")
            vals[r] = post[r]
        return self.napp(s.succ, mem, vals, memfn, self.succ_slots(pc, s),
                         self.fuel_arg(pc, s.succ), tfn)

    def tail_body(self, pc, s, memfn):
        """lane float-sf6: a tail node's value (the callee's summary value) or
        memory (the callee's patches of the node's memory: its window, at the
        routine's entry `sp`, and its outer word)."""
        c = s_callee(s)
        post = {r: self.subst(pc, e) for r, e in s.post.items()}
        mem = self.subst(pc, s.mem)
        fmt = self.call_fmt(pc, s, post, mem)
        if not memfn:
            return c.val.format(**fmt)
        if not c.frame:
            return mem
        out = f"memPatch ({mem}) ({c.mf.format(**fmt)}) ({fmt['sp']} - {c.frame}) {c.frame}"
        if c.outer:
            out = f"memPatch ({out}) ({c.mf.format(**fmt)}) {c.outer[0]} {c.outer[1]}"
        return out

    def succ_slots(self, pc, s):
        """The values of the successor's slot parameters: a slot this segment
        stores, its datum; otherwise this node's parameter."""
        st = self.seg_stores(pc, s)
        return {o: (self.subst(pc, st[o]) if o in st else f"vs{o[2:]}") for o in self.slots_in[s.succ]}

    def sp_nat(self, pc, s=None):
        """`sp` at node `pc` (after segment `s`'s prologue, if it has one) as
        a `Nat` (a framed callee's `s`)."""
        if not self.framed():
            raise SystemExit(f"0x{pc:x}: a framed callee needs a framed caller")
        inside = self.inside(pc) if s is None else self.off[pc] - s.sp_delta != 0
        return f"(s - {self.F})" if inside else "s"

    def call_g(self, pc, s, post=None):
        """The caller's frame at a call (`{g}`): the caller's `g`, or, where
        the routine holds its own values in callee-saved registers (lane
        F1-F7: `fmod`'s `s0`-`s2`, `PRO_SAVES`), the frame of the current
        registers (`SFrame.mk`, the spilled ones from the segment's post-state)."""
        if "{g}" not in (s_callee(s).args + (s_callee(s).mf or "")):
            return "g"
        sp = self.sp_after.get((pc, id(s)), frozenset())
        if not sp:
            return "g"
        if self.fn not in PRO_SAVES or post is None:
            raise SystemExit(f"{s.name}: a callee stores the caller's frame while it is spilled")
        return "(SFrame.mk " + " ".join(f"({post[r]})" if r in sp else f"g.{f}"
                                        for r, f in FRAME.items()) + ")"

    def call_fmt(self, pc, s, post, mem):
        """The format arguments of a call node's callee."""
        c = s_callee(s)
        fmt = {f"a{i}": post[10 + i] for i in range(c.nargs)}
        fmt["m"], fmt["r"] = mem, ("r" if s.kind == "tail" else f"0x{s.hi:08x}#64")
        fmt["sp"] = self.sp_nat(pc, s) if c.frame else ""
        fmt["g"] = self.call_g(pc, s, post)
        return fmt

    def ndef(self, pc, memfn=False, tfn=False):
        ss = self.nodes[pc]
        ty = "Mem" if memfn else "Bool" if tfn else "BitVec 64"
        if pc in self.jt:
            ix = self.val(pc, self.jt[pc][2])
            b = ""
            for s in ss[:-1]:
                b += f"if {ix}.toNat = {s.k} then\n    {self.body(pc, s, memfn, tfn)}\n  else "
            b += f"\n    {self.body(pc, ss[-1], memfn, tfn)}"
        elif len(ss) == 1:
            b = self.body(pc, ss[0], memfn, tfn)
        else:
            t = next(s for s in ss if s.guard[1])
            n = next(s for s in ss if not s.guard[1])
            b = (f"if {self.subst(pc, t.guard[0])} = true then\n    {self.body(pc, t, memfn, tfn)}\n"
                 f"  else\n    {self.body(pc, n, memfn, tfn)}")
        name = self.mn(pc) if memfn else self.tn(pc) if tfn else self.dn(pc)
        nc = "noncomputable " if memfn and self.noncomp else ""
        if pc in self.cyc:
            # lane float-sf5: structural recursion on the fuel (`Kit/FnLoop.lean`)
            junk = "m" if memfn else "false" if tfn else "0#64"
            b = b.replace("\n", "\n  ")
            return (f"{nc}def {name} {self.nargs(pc, memfn)} : {ty} :=\n  match fuel with\n"
                    f"  | 0 => {junk}\n  | k + 1 =>\n    {b}\n")
        return (f"{nc}def {name} {self.nargs(pc, memfn)} : {ty} :=\n  {b}\n")

    # ----------------------------------------------------------------------
    def lemma_binders(self, pc, k=None, pre_on=True):
        vs = " ".join(f"v{r}" for r in self.live(pc))
        if self.inside(pc) and 1 in self.regs(pc):
            vs = (vs + " v1").strip()
        vs = (vs + " " + " ".join(f"vs{o[2:]}" for o in self.slots_in[pc])).strip()
        bv = f" ({vs} : BitVec 64)" if vs else ""
        # lane float-sf5: the premises, the fuel on a cycle, the termination fact
        pre = (self.prem_binders() + ("(fuel : Nat) " if pc in self.cyc else "")) if pre_on else ""
        ht = ""
        if self.need_t[pc]:
            ht = (f"\n    (hT : {self.napp(pc, fuel='fuel' if pc in self.cyc else None, tfn=True)}"
                  " = true)")
        if self.framed():
            hs = f"(hs : FnSp s {self.W}) (hr : r.toNat % 4 = 0) (hrod : RodataRead m)"
            if self.inside(pc):
                hs += f" (hra : bytesT8 m ({re.sub(r"\bv2\b", self.sp(self.entry), self.ra)}) = r)"
            for o in self.slots_in[pc]:
                hs += f"\n    (hs{o[2:]} : bytesT8 m {self.slot_addr(pc, o)} = vs{o[2:]})"
            for o in self.sv_in[pc]:
                hs += f"\n    (hsv{o[2:]} : bytesT8 m {self.slot_addr(pc, o)} = g.{FRAME[self.sv_slot[o]]})"
            if pc in self.jt and k is None:
                hs += f"\n    (hjt : v{self.jt[pc][2]}.toNat < {self.jt[pc][1]})"
            elif pc in self.jt:
                hs += f"\n    (hk : v{self.jt[pc][2]} = BitVec.ofNat 64 {k})"
            hs += "".join(f"\n    ({n} : {ty})" for n, ty, _ in self.facts)
            return f"{pre}(m : Mem) (o : Array String) (s : Nat) (r : BitVec 64) (g : SFrame){bv}\n    {hs}{ht}"
        fs = "".join(f" ({n} : {ty})" for n, ty, _ in self.facts)
        return f"{pre}(m : Mem) (o : Array String) (r : BitVec 64) (f : HFrame){bv}\n    (hr : r.toNat % 4 = 0){fs}{ht}"

    def seg_app(self, pc, s, neg):
        args = ["_"] * (s.nvars + 2)
        sd = [h for h, _ in self.side(s)]
        for h, _ in s.hyps:
            if h in sd:
                # the i-th of k side conjuncts of `(R && d₁ && … && d_k)`
                i, k = sd.index(h), len(sd)
                args.append("(" + "fn_and_r (" + "fn_and_l (" * (k - 1 - i) + "hTs"
                            + ")" * (k - 1 - i) + "))")
                continue
            if h.startswith("hg"):
                rs = self.guard_slots(pc, s)
                if rs:
                    args.append(f"(by rw [{', '.join(rs)}]; exact {'fn_false hg' if neg else 'hg'})")
                else:
                    args.append("(fn_false hg)" if neg else "hg")
            elif h.startswith("htgt") and pc in self.jt:
                args.append(f"(by rw [{self.jt_tgt(pc, s)}]; decide)")
            elif h.startswith("htgt"):
                args.append("(by rw [fn_tgt hra hr]; exact hr)" if self.framed() and self.inside(pc)
                            else "(by rw [fn_tgt0 hr]; exact hr)")
            elif re.match(r"h(lo|hi|ht|win|al)_", h) and pc in self.jt:
                args.append("(by first | kit_disch | (rw [hk]; decide +kernel))")
            elif re.match(r"h(lo|hi|ht|win|al)_", h):
                args.append(f"(by {DISCH.get(self.fn, 'kit_disch')})")
            else:
                raise SystemExit(f"{s.name}: hypothesis {h}")
        return f"Lua.Vm.Arms.{s.name} {' '.join(args)}"

    def jt_tgt(self, pc, s):
        """Entry `s.k`'s target (`fn_jt_tgt`), the index `hk` fixed."""
        tb = self.jt[pc][0]
        return (f"Lua.Vm.Sim.fn_jt_tgt (a := {tb + 4 * s.k}) (t := 0x{s.succ:08x}#64) hrod "
                "(by rw [hk]; decide +kernel) (by decide) (by decide) (by decide +kernel)")

    def guard_slots(self, pc, s):
        if not self.fwd or not s.guard or not self.inside(pc):
            return []
        return [f"hs{o[2:]}" for o in sorted(set(re.findall(LOAD_RE, s.guard[0])) - {self.ra_off})]

    def succ_app(self, pc, cur=None, seg=None, ht=None):
        n = len(self.live(pc)) + (1 if self.inside(pc) and 1 in self.regs(pc) else 0)
        vs = " ".join(["_"] * n)
        if self.slots_in[pc]:
            sv = self.succ_slots(cur, seg)
            vs = (vs + " " + " ".join(f"({sv[o]})" for o in self.slots_in[pc])).strip()
        # lane float-sf5: the premises, the fuel (one less on the cycle), the
        # termination fact (`ht`: the current node's `hT` unfolded)
        pre = self.prem_args() + (f"{self.fuel_arg(cur, pc)} " if pc in self.cyc else "")
        name = self.ln(pc)
        if cur is not None and self.same(cur, pc):
            # the induction hypothesis of the cycle's block (`cyc_block`)
            name, pre = f"ih.{self.ln(pc)}", ""
        post = f" {ht}" if self.need_t[pc] else ""
        if self.framed():
            hs = f"hs hr (by {self.rod})" + (f" (by {self.ra_t})" if self.inside(pc) else "")
            hs += "".join(f" (by {self.ra_t})" for _ in self.slots_in[pc])
            hs += "".join(f" (by {self.ra_t})" for _ in self.sv_in[pc])
            if pc in self.jt:
                # the bound check before the table: `bltu n-1, idx` not taken
                if not (seg and seg.guard and not seg.guard[1] and seg.guard[0].startswith("zopz0zI_u ")):
                    raise SystemExit(f"0x{pc:x}: a jump table not reached by its bound check")
                hs += " (Lua.Vm.Sim.fn_jt_bound (fn_false hg) (by decide))"
            hs += "".join(f" {n}" if tac is None else f" (by {tac})" for n, _, tac in self.facts)
            return f"{name} {pre}_ _ s r g {vs} {hs}{post}".replace("  ", " ")
        fs = "".join(f" {n}" if tac is None else f" (by {tac})" for n, _, tac in self.facts)
        return f"{name} {pre}_ _ r f {vs} hr{fs}{post}".replace("  ", " ")

    def branch_proof(self, pc, s, neg, ind):
        I = " " * ind
        pol = ", if_neg hg" if neg else ", if_pos hg" if s.guard else ""
        out = []
        if self.side(s):
            out.append(f"{I}have hTs := hT")
            out.append(f"{I}rw [{self.tn(pc)}{pol}] at hTs")
        out += [f"{I}obtain ⟨_, acc, h⟩ := Vsa.Sim.SegSt.run acc h (by pins_of h)",
                f"{I}  ({self.seg_app(pc, s, neg)})"]
        if getattr(s, "wm4_reads", False):
            out.append(f"{I}simp (disch := fn_odisch) only [bytesT8_wm4_far] at h")
        if self.sv_slot and self.inside(pc):
            sv = sorted(set(re.findall(SV_RE, " ".join(s.post.values()))) & set(self.sv_slot))
            if sv:
                out.append(f"{I}rw [{', '.join(f'Lua.Vm.Sim.fn_sv_ld hsv{o[2:]}' for o in sv)}] at h")
        if self.fwd and self.inside(pc):
            ld = sorted(set(re.findall(LOAD_RE, " ".join(list(s.post.values()) + [s.mem])))
                        - {self.ra_off} - set(self.sv_slot))
            if ld:
                out.append(f"{I}rw [{', '.join(f'hs{o[2:]}' for o in ld)}] at h")
        if pc in self.jt:
            out.append(f"{I}have h := h.at (pc' := 0x{s.succ:08x}#64) ({self.jt_tgt(pc, s)})")
            out.append(f"{I}have hk' := Lua.Vm.Sim.fn_jt_idx hk (by decide)")
            unfold = (f"rw [{self.dn(pc)}, {self.mn(pc)}]; "
                      f"simp only [hk', Nat.reduceEqDiff, ↓reduceIte]")
        elif self.framed():
            unfold = f"rw [{self.dn(pc)}, {self.mn(pc)}]" + (
                "; simp only [if_neg hg]" if neg else "; simp only [if_pos hg]" if s.guard else "")
        else:
            unfold = f"rw [{self.dn(pc)}" + (", if_neg hg]" if neg else ", if_pos hg]" if s.guard else "]")
        if s.kind == "tail":
            return out + self.tail_proof(pc, s, unfold, I)
        if s.kind == "ret":
            if self.framed() and self.inside(pc):
                out.append(f"{I}rw [fn_sp_restore s ({self.pro_imm}#12) ({s.sp_imm}#12) (by decide)] at h")
                tgt = "fn_tgt hra hr"
            else:
                tgt = "fn_tgt0 hr"
            out.append(f"{I}refine ⟨_, acc, ?_⟩")
            out.append(f"{I}{unfold}")
            if self.framed():
                if self.fn in OUTER and "writeMap4" in s.mem:
                    # lane float-sf6: the outer store in the returning segment
                    out.append(f"{I}rw [memPatch_ret_wm4 (by fn_odisch) (by fn_odisch)]")
                else:
                    out.append(f"{I}rw [memPatch_self" + (", memPatch_self]" if self.fn in OUTER else "]"))
            out.append(f"{I}exact (h.at ({tgt})).repin (by pins_of h)")
            return out
        framed_call = s.kind == "call" and s_callee(s).frame
        if s.kind == "call":
            c = s_callee(s)
            post = {r: self.subst(pc, e) for r, e in s.post.items()}
            args = c.args.format(sp=self.sp_nat(pc, s) if c.frame else "", g=self.call_g(pc, s, post),
                                 fsp="(fn_sp_in hs (by decide) (by decide))", hr="(by decide)").replace(
                "(by fn_rod)", f"(by {self.rod})")
            # a framed callee's `s` is the caller's `sp` as a `Nat`: its pin
            # put in front (`SegSt.pin_sp`), and back after the return
            spn = (f"(Lua.Vm.Sim.fn_sp_nat s ({self.pro_imm}#12) {self.F} (by decide) (by omega) "
                   "(by omega) (by omega))")
            if c.frame:
                out.append(f"{I}have h := h.pin_sp (pin_eq (by pin_of h) {spn})")
            # a kept register dead here: pinned at whatever it holds
            for r in c.keeps:
                if r not in s.post:
                    out.append(f"{I}pin_gpr h {r} Register.x{r}")
            out.append(f"{I}obtain ⟨_, acc, h⟩ := Vsa.Sim.SegSt.call acc h (by pins_of h)")
            out.append(f"{I}  ({c.summ} {args})")
            if c.frame:
                out.append(f"{I}have h := h.pin_sp (pin_eq (by pin_of h) {spn}.symm)")
        ht = None
        if self.need_t[s.succ]:
            ht = f"(by rw [{self.tn(pc)}{pol}] at hT; exact hT)"
            if self.side(s):
                ht = "(" + "fn_and_l (" * len(self.side(s)) + "hTs" + ")" * len(self.side(s)) + ")"
        out.append(f"{I}obtain ⟨_, acc, h⟩ := Vsa.Sim.SegSt.run acc h (by pins_of h)")
        out.append(f"{I}  ({self.succ_app(s.succ, pc, s, ht)})")
        out.append(f"{I}refine ⟨_, acc, ?_⟩")
        out.append(f"{I}{unfold}")
        if framed_call:
            out.append(f"{I}simp (disch := kit_disch) only [memPatch_patch_in] at h")
        if "writeMap8" in s.mem:
            out.append(f"{I}simp (disch := kit_disch) only [memPatch_wm8_in] at h")
        if "writeMap4" in s.mem:
            # lane F1-F7: a store outside the frame, overwritten by the outer patch
            out.append(f"{I}simp (disch := fn_odisch) only [memPatch_wm4_outer] at h")
        out.append(f"{I}exact h")
        return out

    def tail_proof(self, pc, s, unfold, I):
        """lane float-sf6: a tail node's proof: the frame popped (`sp`, `ra`
        restored), the callee's summary, the routine's patches of its memory
        (`memPatch_tail`, `Kit/FnTail.lean`)."""
        c = s_callee(s)
        out = []
        if self.framed() and self.inside(pc):
            out.append(f"{I}rw [fn_sp_restore s ({self.pro_imm}#12) ({s.sp_imm}#12) (by decide)] at h")
            out.append(f"{I}rw [Lua.Vm.Sim.fn_sv_ld hra] at h")
        post = {r: self.subst(pc, e) for r, e in s.post.items()}
        args = c.args.format(sp="s", g=self.call_g(pc, s, post),
                             fsp=f"(Lua.Vm.Sim.fn_sp_le (W' := {c.frame}) hs (by decide))", hr="hr").replace("(by fn_rod)", f"(by {self.rod})")
        out.append(f"{I}obtain ⟨_, acc, h⟩ := Vsa.Sim.SegSt.call acc h (by pins_of h)")
        out.append(f"{I}  ({c.summ} {args})")
        out.append(f"{I}refine ⟨_, acc, ?_⟩")
        out.append(f"{I}{unfold}")
        if self.framed():
            if not c.frame:
                out.append(f"{I}rw [memPatch_self" + (", memPatch_self]" if self.fn in OUTER else "]"))
            elif self.fn in OUTER and c.outer:
                out.append(f"{I}rw [memPatch_tail_outer (by omega) (by omega)]")
            elif self.fn in OUTER:
                raise SystemExit(f"{s.name}: an outer routine's tail callee without the outer word")
            else:
                out.append(f"{I}rw [memPatch_tail (by omega) (by omega)]")
        out.append(f"{I}exact h.repin (by pins_of h)")
        return out

    def binder_args(self, pc):
        """A framed node lemma's binders, as the arguments that pass them on."""
        vs = [f"v{r}" for r in self.live(pc)] + (["v1"] if self.inside(pc) and 1 in self.regs(pc) else [])
        vs += [f"vs{o[2:]}" for o in self.slots_in[pc]]
        hs = ["hs", "hr", "hrod"] + (["hra"] if self.inside(pc) else [])
        hs += [f"hs{o[2:]}" for o in self.slots_in[pc]] + [f"hsv{o[2:]}" for o in self.sv_in[pc]]
        hs += [n for n, _, _ in self.facts]
        return " ".join(["m", "o", "s", "r", "g"] + vs + hs)

    def jt_entries(self, pc):
        """A jump node's entries, each in its own declaration (one segment run
        and the target's lemma: the node's sixteen in one declaration exceed
        the elaboration budget)."""
        out = []
        for s in self.nodes[pc]:
            L = [f"theorem {self.ln(pc)}_{s.k} {self.lemma_binders(pc, s.k)} :",
                 f"    Triple (SegSt 0x{pc:08x}#64 {self.pins(pc)} (ArmPay m o))",
                 f"      ({self.post(pc)}) := by",
                 "  intro c h",
                 "  have acc := Vsa.Machine.Steps.refl c",
                 "  fn_sp_facts"]
            L += self.branch_proof(pc, s, False, 2)
            out.append("\n".join(L) + "\n")
        return "\n".join(out)

    def lemma(self, pc):
        ss = self.nodes[pc]
        head = [(f"/-- **The summary**: the entry node's lemma, the lifted function `F`. -/\n" if pc == self.entry else "") + f"theorem {self.ln(pc)} {self.lemma_binders(pc)} :",
                f"    Triple (SegSt 0x{pc:08x}#64 {self.pins(pc)} (ArmPay m o))",
                f"      ({self.post(pc)}) := by"]
        L = ["  intro c h",
             "  have acc := Vsa.Machine.Steps.refl c"]
        if self.framed():
            L.append("  fn_sp_facts")
        if self.fn in OUTER:
            L.append("  fn_imp_facts")
        if pc in self.jt:
            # the index enumerated from the top entry down (`fn_jt_split`),
            # each entry its own lemma
            args = self.binder_args(pc)
            for s in reversed(ss[1:]):
                L.append("  rcases Lua.Vm.Sim.fn_jt_split hjt with hk | hjt")
                L.append(f"  · exact {self.ln(pc)}_{s.k} {args} hk c h")
            L.append(f"  exact {self.ln(pc)}_0 {args} (Lua.Vm.Sim.fn_jt_zero hjt) c h")
            if pc in self.cyc or self.prem or self.need_t[pc]:
                raise SystemExit(f"0x{pc:x}: a jump node on a cycle or under a premise")
            return self.jt_entries(pc) + "\n" + "\n".join(head + L) + "\n"
        elif len(ss) == 1:
            L += self.branch_proof(pc, ss[0], False, 2)
        else:
            t = next(s for s in ss if s.guard[1])
            n = next(s for s in ss if not s.guard[1])
            L.append(f"  by_cases hg : {self.subst(pc, t.guard[0])} = true")
            b1 = self.branch_proof(pc, t, False, 4)
            b2 = self.branch_proof(pc, n, True, 4)
            L.append("  · " + b1[0].lstrip())
            L += b1[1:]
            L.append("  · " + b2[0].lstrip())
            L += b2[1:]
        if pc in self.cyc:
            return L
        return "\n".join(head + L) + "\n"

    def binder_names(self, pc):
        """The names `lemma_binders` binds (without premises and fuel)."""
        names = []
        for grp in re.findall(r"\(([^():]+) : ", self.lemma_binders(pc, pre_on=False)):
            names += grp.split()
        return names

    def cyc_block(self, g):
        """lane float-sf5: the node lemmas of the cycle `g`, by induction on
        the fuel: a structure `Cyc_<h> fuel` with one field per node (its
        lemma at that fuel), proved for every fuel by `induction` (fuel 0
        excluded by `hT`: `T_<pc> 0 … = false`; at `k + 1` each node's proof
        takes the cycle's successors from the hypothesis `ih` at `k`), then
        each node lemma as its projection. (A `mutual` block of theorems by
        structural recursion compiles the proof terms through `transform`,
        past the heartbeat budget.)"""
        h = g[0]
        cn = f"Cyc_{h:08x}"
        pb, pa = self.prem_binders(), self.prem_args()
        fields, zero, succ, projs = [], [], [], []
        for pc in g:
            st = (f"  {self.ln(pc)} : ∀ {self.lemma_binders(pc, pre_on=False)},\n"
                  f"    Triple (SegSt 0x{pc:08x}#64 {self.pins(pc)} (ArmPay m o))\n"
                  f"      ({self.post(pc)})")
            fields.append(st)
            names = " ".join(self.binder_names(pc))
            zero.append(f"    · intro {names}\n      rw [{self.tn(pc)}] at hT; cases hT")
            body = self.lemma(pc)
            succ.append(f"    · intro {names}\n" + "\n".join("    " + x for x in body))
            projs.append(f"theorem {self.ln(pc)} {pb}(fuel : Nat) {self.lemma_binders(pc, pre_on=False)} :\n"
                         f"    Triple (SegSt 0x{pc:08x}#64 {self.pins(pc)} (ArmPay m o))\n"
                         f"      ({self.post(pc)}) :=\n"
                         f"  ({'cyc' + cn[3:]} {pa}fuel).{self.ln(pc)} {names}\n")
        anon = "⟨" + ", ".join("?_" for _ in g) + "⟩"
        if self.fn in CYC_SPLIT:
            return self.cyc_split(g, cn, pb, pa, fields, zero, anon, projs)
        out = [f"/-- The node lemmas of the cycle at `0x{h:08x}` at fuel `fuel`. -/",
               f"structure {cn} {pb}(fuel : Nat) : Prop where"] + fields + [
               "",
               f"theorem {'cyc' + cn[3:]} {pb}: ∀ fuel, {cn} {pa}fuel := by",
               "  intro fuel",
               "  induction fuel with",
               "  | zero =>",
               f"    refine {anon}"] + zero + [
               "  | succ k ih =>",
               f"    refine {anon}"] + succ + [""] + projs
        return "\n".join(out)

    def cyc_split(self, g, cn, pb, pa, fields, zero, anon, projs):
        """lane float-sf6 (`CYC_SPLIT`): `cyc_block` with each node's step
        (its lemma at fuel `k + 1` from the cycle's lemmas at `k`) in its own
        declaration `cs_<pc>`, so that no declaration holds more than one
        node's proof (a 13-node cycle in one declaration exceeds the budget)."""
        steps = []
        for pc, st in zip(g, fields):
            stmt = re.sub(r"\bfuel\b", "(k + 1)", st.split(" : ", 1)[1])
            names = " ".join(self.binder_names(pc))
            steps.append(f"theorem cs_{pc:08x} {pb}(k : Nat) (ih : {cn} {pa}k) :\n  {stmt} := by\n"
                         f"  intro {names}\n" + "\n".join(self.lemma(pc)) + "\n")
        out = [f"/-- The node lemmas of the cycle at `0x{g[0]:08x}` at fuel `fuel`. -/",
               f"structure {cn} {pb}(fuel : Nat) : Prop where"] + fields + [""] + steps + [
               f"theorem {'cyc' + cn[3:]} {pb}: ∀ fuel, {cn} {pa}fuel := by",
               "  intro fuel",
               "  induction fuel with",
               "  | zero =>",
               f"    refine {anon}"] + zero + [
               "  | succ k ih =>",
               "    exact ⟨" + ", ".join(f"cs_{pc:08x} {pa}k ih" for pc in g) + "⟩", ""] + projs
        return "\n".join(out)

    # ----------------------------------------------------------------------
    def summary(self):
        return ""

    def groups(self):
        """`self.order` cut into its cycles (one group each) and single nodes."""
        out = []
        for pc in self.order:
            if out and pc in self.cyc and self.same(out[-1][-1], pc):
                out[-1].append(pc)
            else:
                out.append([pc])
        return out

    @staticmethod
    def mutual(items):
        if len(items) == 1 and "match fuel with" not in items[0]:
            return items[0]
        return "mutual\n\n" + "\n".join(items) + "\nend\n"

    def files(self):
        """{path: text}: one module, or, past `CHUNK` nodes, the lifted
        functions (`<Mod>/Defs`), the node lemmas in chunks of `CHUNK`
        (`<Mod>/L<k>`, in proof order) and the summary (`<Mod>`), so that no
        module's elaboration holds more than `CHUNK` node proofs."""
        # lane float-sf5: a cycle's definitions and lemmas are one `mutual`
        # block (structural recursion on the fuel); everything else one item
        groups = self.groups()
        defs = "\n".join(self.mutual([self.ndef(pc) for pc in g]) for g in groups)
        if any(self.need_t.values()):
            defs += "\n" + "\n".join(self.mutual([self.ndef(pc, tfn=True) for pc in g if self.need_t[pc]])
                                      for g in groups if any(self.need_t[pc] for pc in g))
        if self.framed():
            defs += "\n" + "\n".join(self.mutual([self.ndef(pc, True) for pc in g]) for g in groups)
        lems = [self.cyc_block(g) if g[0] in self.cyc else self.lemma(g[0]) for g in groups]
        nseg = len(self.segs)
        kind = (f"a {self.F}-byte frame below `sp`, the memory `memPatch`ed there"
                if self.framed() else "a leaf: the memory and the caller's frame kept")
        if self.W != self.F:
            kind += f" ({self.W} bytes with its framed callees' frames)"
        imports = "import Lua.Vm.Sim.Kit.Fn\n"
        if self.patch or self.fwd:
            imports += "import Lua.Vm.Sim.Kit.FnCall\n"
        if self.fn in OUTER:
            imports += "import Lua.Vm.Sim.Kit.FnOuter\n"
        if any(s.kind == "tail" for s in self.segs) or (self.fn in OUTER and self.fn in SF6):
            imports += "import Lua.Vm.Sim.Kit.FnTail\n"
        if self.cyc:
            imports += "import Lua.Vm.Sim.Kit.FnLoop\n"
        callees = sorted({s.callee for s in self.segs if s.kind in ("call", "tail")})
        for e in callees:
            imports += f"import {callee_of(e).imp}\n"
        imports += f"import Lua.Vm.Arms.Segs.H{self.fn.lstrip('_')}\n"
        doc = (f"`{self.fn}` (entry `0x{self.entry:08x}`): its {nseg} generated segments\n"
               f"(`Lua/Vm/Arms/Segs/H{self.fn.lstrip('_')}.lean`) folded into {len(self.order)} nodes, {kind}.\n"
               "`N_<pc>` is the lifted function of the node at `pc`, `n_<pc>` its lemma; at the\n"
               "entry they are `F` (the lifted function level 2 relates to `F64`; `Fm`, `Nm_<pc>`\n"
               "a framed helper's memory) and `sum` (the summary).")
        opens = ("open LeanRV64DExecutable LeanRV64DExecutable.Functions Sail ConcurrencyInterfaceV1 Vsa\n"
                 "open Vsa.Sim Vsa.Logic\nopen Lua.Vm.Sim\n")
        opaque = [n for e in callees for n in callee_of(e).opaque]
        if opaque:
            opens += ("\n-- the callees' lifted functions are their summaries' values, never unfolded\n"
                      f"attribute [local irreducible] {' '.join(opaque)}\n")
        ns = f"Lua.Vm.Fn.{self.mod}"

        def module(imp, what, body):
            return (f"{imp}\n/-! {HEADER}\n\n{doc}\n\n{what}\n-/\n\n{opens}\n"
                    f"namespace {ns}\n\n{body}\nend {ns}\n")
        if len(self.order) <= CHUNK and not self.cyc:
            return {OUT / f"{self.mod}.lean": module(
                imports, "This module: the whole fold.",
                defs + "\n" + "\n".join(lems) + "\n" + self.summary())}
        out = {OUT / self.mod / "Defs.lean": module(imports, "This module: the lifted functions.", defs)}
        prev = f"{ns}.Defs"
        # chunks of at most `CHUNK` node lemmas, a `mutual` block never split
        chunks, cur, n = [], [], 0
        for g, lem in zip(groups, lems):
            if cur and n + len(g) > CHUNK:
                chunks.append(cur)
                cur, n = [], 0
            cur.append(lem)
            n += len(g)
        if cur:
            chunks.append(cur)
        for k, ch in enumerate(chunks):
            out[OUT / self.mod / f"L{k}.lean"] = module(
                f"import {prev}\n", f"This module: node lemmas, chunk {k} of {len(chunks)}.",
                "\n".join(ch))
            prev = f"{ns}.L{k}"
        out[OUT / f"{self.mod}.lean"] = module(f"import {prev}\n", "This module: the index.", "")
        return out


CHUNK = 40
# lane float-sf6: the terminal node kinds (a `ret`; a tail jump to a summarised
# callee), and the routines whose `j <callee>` are tail nodes
TERM = ("ret", "tail")
TAILS = {"xflow", "__math_oflow", "__math_uflow"}
# lane float-sf6: the routines whose cycle blocks put each node's step in its
# own declaration (`Fn.cyc_split`)
CYC_SPLIT = {"__ieee754_sqrt"}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--only", default="")
    a = ap.parse_args()
    drift = False
    for fn in ROUTINES:
        if a.only and fn not in a.only.split(","):
            continue
        f = Fn(fn)
        files = f.files()
        for path, t in files.items():
            if a.check:
                if not path.exists() or path.read_text() != t:
                    print(f"drift: {path.relative_to(ROOT)}")
                    drift = True
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(t)
        if not a.check:
            print(f"{fn}: {len(f.order)} nodes, {len(f.segs)} segments, {len(files)} modules")
    return 1 if drift else 0


if __name__ == "__main__":
    sys.exit(main())
