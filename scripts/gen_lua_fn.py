#!/usr/bin/env python3
"""Whole-function summaries of loop-free helpers, folded over their generated
segments (lane float-m0; FLOAT-DESIGN.md §3, level 1).

`scripts/syi/gen_fn.py` refuses functions over 150 instructions (`__adddf3`
has 418) and targets the WHILE ELF's code pins; this is its fold over the
Lua ELF's helper segments (`Lua.Vm.Arms.seg_*`, `scripts/gen_lua_arms.py`
`HELPERS`), linear in the segments:

* a **node** per segment entry pc (one segment, or a branch's two polarities
  `_t`/`_n`);
* its **lifted function** `N_<pc>`: the result (and, for a helper with a
  stack frame, the memory) as a function of the node's live registers: the
  successor's function applied to the segment's post-state, an `if` on the
  branch guard, the callee's summary at a call (`__clzdi2`: `clz64`);
* its **node lemma** `n_<pc>`: the segment (its side conditions discharged in
  the lemma: guards from the case split, addresses by `kit_disch` over the
  stack facts `FnSp`), then the successor's node lemma; each in its own
  declaration.

A helper with a frame (`addi sp, sp, -F`: `__floatsidf`, `__adddf3`, …)
states `sp` as `BitVec.ofNat 64 s`, its nodes inside the frame carry the
saved `ra` (`hra`), and its memory is `memPatch m (N …).2 (s - F) F`
(`Lua/Vm/Sim/Kit/Fn.lean`): the entry memory outside its frame on every
path. A leaf helper (`__eqdf2`, `__ledf2`, `__gedf2`, `__fixdfdi`) keeps
the memory and the caller's frame `HFrame`.

The summary `sum` is the entry node's lemma, `F` its lifted function (for a
framed helper, the result and the memory), which level 2 relates to `F64`.
No other declaration restates `F` (a definitional unfolding of the lifted
functions is exponential in the paths: the kernel's projection reduction
would unfold them).

Output (GENERATED, `--check` reports drift):
    Lua/Vm/Fn/<Name>.lean

    python3 scripts/gen_lua_fn.py [--check] [--only __floatsidf]
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))
sys.path.insert(0, str(ROOT / "scripts/syi"))
import gen_lua_arms as gla          # noqa: E402
import gen_segment                  # noqa: E402

OUT = ROOT / "Lua/Vm/Fn"
HEADER = "GENERATED by scripts/gen_lua_fn.py -- do not edit."

# helper -> (module name, entry, frame bytes (0: a leaf), argument registers)
ROUTINES = {
    "__floatsidf": ("Floatsidf", 0x8002f0f8, 32, [10]),
    "__floatdidf": ("Floatdidf", 0x8002f200, 32, [10]),
    "__fixdfdi": ("Fixdfdi", 0x8002f188, 0, [10]),
    "__eqdf2": ("Eqdf2", 0x8002e350, 0, [10, 11]),
    "__ledf2": ("Ledf2", 0x8002e460, 0, [10, 11]),
    "__gedf2": ("Gedf2", 0x8002e3c0, 0, [10, 11]),
    "__adddf3": ("Adddf3", 0x8002d7a8, 48, [10, 11]),
    "__subdf3": ("Subdf3", 0x8002e9d0, 48, [10, 11]),
}
# the summarised callees: entry -> (summary, value function)
CALLEES = {0x8002f7ec: ("Lua.Vm.Sim.clzdi2_sum", "Lua.Vm.Sim.clz64")}

# the callee-saved registers: register -> field of `HFrame`/`SFrame`
FRAME = {3: "gp", 8: "s0", 9: "s1", 18: "s2", 19: "s3", 20: "s4", 21: "s5", 22: "s6",
         23: "s7", 24: "s8", 25: "s9", 26: "s10", 27: "s11"}


def args_of(text):
    """The top-level parenthesised arguments of `f (a) (b) …` as strings."""
    out, depth, cur = [], 0, None
    for ch in text:
        if ch == "(":
            depth += 1
            if depth == 1:
                cur = []
                continue
        elif ch == ")":
            depth -= 1
            if depth == 0:
                out.append("".join(cur))
                cur = None
                continue
        if depth >= 1 and cur is not None:
            cur.append(ch)
    return out


def wm8_chain(mem):
    """`writeMap8 (writeMap8 (m0) (a1) (d1)) (a2) (d2)` -> [(a1, d1), (a2, d2)]."""
    stores = []
    while mem.startswith("writeMap8 "):
        inner, a, d = args_of(mem[len("writeMap8 "):])[:3]
        stores.insert(0, (a, d))
        mem = inner.strip()
    if mem != "m0":
        raise SystemExit(f"memory {mem[:60]}: not a writeMap8 chain over m0")
    return stores


class Seg:
    def __init__(self, name, lo, hi, spec):
        em = gen_segment.SegmentEmitter(spec)
        em.emit()
        self.name, self.lo, self.hi = name, lo, hi
        self.suf = name[21:]
        self.pre = [int(p["reg"][1:]) for p in spec["pins"]]
        self.post = {int(r[1:]): v for r, v in em.pins}
        self.end = em.end_pc
        self.mem = em.mem_expr or "m0"
        head = em.body_text.split(":= by")[0]
        m = re.search(r"^    \(([v\d ]+) : BitVec 64\)$", head, re.M)
        self.nvars = len(m.group(1).split()) if m else 0
        self.hyps = re.findall(r"^    \((h\w+) : (.*)\)$", head, re.M)
        lit = re.match(r"^\(?(0x[0-9a-f]+)#64\)?$", self.end)
        self.kind = "goto"
        self.succ = int(lit.group(1), 16) if lit else None
        if self.succ is None:
            self.kind = "ret"
        elif self.succ in CALLEES:
            self.kind = "call"
            self.callee = self.succ
            self.succ = hi
        elif not (gla_lo[0] <= self.succ < gla_lo[1]):
            raise SystemExit(f"{name}: jump out of the helper to 0x{self.succ:x}")
        self.guard = None
        for h, t in self.hyps:
            if h.startswith("hg"):
                g = re.match(r"^(.*) = (true|false)$", t)
                self.guard = (g.group(1), g.group(2) == "true")
        self.sp_delta = 0
        x2 = self.post.get(2, "v2")
        if x2 != "v2":
            m = re.match(r"^\(v2 \+ sign_extend \(m := 64\) \((0x[0-9a-f]+)#12\)\)$", x2)
            if not m:
                raise SystemExit(f"{name}: sp becomes {x2}")
            k = int(m.group(1), 16)
            self.sp_delta = k - 4096 if k >= 2048 else k
            self.sp_imm = m.group(1)


gla_lo = [0, 0]


class Fn:
    def __init__(self, fn):
        self.fn = fn
        self.mod, self.entry, self.F, self.args = ROUTINES[fn]
        lo, hi = next((a, b) for f, _, a, b, *_ in gla.HELPERS if f == fn)
        gla_lo[0], gla_lo[1] = lo, hi
        self.segs = [Seg(n, a, b, s) for n, a, b, s in gla.helper_specs(fn)]
        self.nodes = {}
        for s in self.segs:
            self.nodes.setdefault(s.lo, []).append(s)
        # the frame state of every node (0: before the prologue, F: inside the frame)
        self.off, self.ra = {self.entry: 0}, None
        work = [self.entry]
        while work:
            pc = work.pop()
            for s in self.nodes[pc]:
                if s.kind == "ret":
                    continue
                o = self.off[pc] - s.sp_delta
                if s.sp_delta:
                    if not self.F or s.sp_delta != -self.F:
                        raise SystemExit(f"{s.name}: frame {s.sp_delta}")
                    self.pro_imm = s.sp_imm
                    for a, d in wm8_chain(s.mem):
                        if d == "sdData_val v1":
                            self.ra = a
                    if self.ra is None:
                        raise SystemExit(f"{s.name}: the prologue does not save ra")
                if s.succ in self.off and self.off[s.succ] != o:
                    raise SystemExit(f"0x{s.succ:x}: frame {self.off[s.succ]} and {o}")
                if s.succ not in self.off:
                    self.off[s.succ] = o
                    work.append(s.succ)
        # topological order: successors first
        self.order, seen = [], set()

        def visit(pc):
            if pc in seen:
                return
            seen.add(pc)
            for s in self.nodes[pc]:
                if s.kind != "ret":
                    visit(s.succ)
            self.order.append(pc)
        visit(self.entry)

    # ----------------------------------------------------------------------
    def dn(self, pc):
        """The lifted function of node `pc` (`F` at the entry)."""
        return "F" if pc == self.entry else f"N_{pc:08x}"

    def ln(self, pc):
        """The lemma of node `pc` (`sum` at the entry)."""
        return "sum" if pc == self.entry else f"n_{pc:08x}"

    def framed(self):
        return self.F > 0

    def inside(self, pc):
        return self.off[pc] != 0

    def regs(self, pc):
        """The registers pinned at node `pc` (the union of its polarities')."""
        rs = []
        for s in self.nodes[pc]:
            for r in s.pre:
                if r not in rs:
                    rs.append(r)
        return rs

    def live(self, pc):
        """The node's registers that are its lifted function's arguments."""
        return sorted(r for r in self.regs(pc) if r not in FRAME and r not in (1, 2))

    def sp(self, pc):
        if not self.framed():
            return "f.sp"
        if self.inside(pc):
            return f"(BitVec.ofNat 64 s + sign_extend (m := 64) ({self.pro_imm}#12))"
        return "(BitVec.ofNat 64 s)"

    def val(self, pc, r):
        """The node's expression for register `r`."""
        if r == 2:
            return self.sp(pc)
        if r == 1:
            return "v1" if self.framed() and self.inside(pc) else "r"
        if r in FRAME:
            return f"{'g' if self.framed() else 'f'}.{FRAME[r]}"
        return f"v{r}"

    def subst(self, pc, text):
        text = re.sub(r"\bv(\d+)\b", lambda m: self.val(pc, int(m.group(1))), text)
        return re.sub(r"\bm0\b", "m", text)

    def nargs(self, pc):
        """The lifted function's parameters (as binders)."""
        vs = " ".join(f"v{r}" for r in self.live(pc))
        bv = f" ({vs} : BitVec 64)" if vs else ""
        if self.framed():
            return f"(m : Mem) (s : Nat) (r : BitVec 64){bv}"
        return bv.strip()

    def napp(self, pc, mem="m", vals=None):
        vals = vals if vals is not None else {r: f"v{r}" for r in self.live(pc)}
        a = " ".join(f"({vals[r]})" if not re.fullmatch(r"v\d+", vals[r]) else vals[r]
                     for r in self.live(pc))
        if self.framed():
            return f"{self.dn(pc)} ({mem}) s r {a}".rstrip()
        return f"{self.dn(pc)} {a}".rstrip()

    def pins(self, pc):
        """The node lemma's pin list."""
        out = [f"⟨Register.x{r}, v{r}⟩" for r in self.live(pc)]
        if 1 in self.regs(pc):
            out.append(f"⟨Register.x1, {self.val(pc, 1)}⟩")
        if self.framed():
            out.append(f"⟨Register.x2, {self.sp(pc)}⟩")
            out += [f"⟨Register.x{r}, g.{f}⟩" for r, f in FRAME.items()]
            return "[" + ", ".join(out) + "]"
        return "(" + " :: ".join(out + ["f.pins"]) + ")"

    def post(self, pc):
        app = self.napp(pc)
        if self.framed():
            pins = [f"⟨Register.x10, ({app}).1⟩", "⟨Register.x2, BitVec.ofNat 64 s⟩"]
            pins += [f"⟨Register.x{r}, g.{f}⟩" for r, f in FRAME.items()]
            mem = f"memPatch m ({app}).2 (s - {self.F}) {self.F}"
            return f"SegSt r [{', '.join(pins)}] (ArmPay ({mem}) o)"
        return f"SegSt r (⟨Register.x10, {app}⟩ :: f.pins) (ArmPay m o)"

    # ----------------------------------------------------------------------
    def body(self, pc, s):
        """The lifted function's value along polarity `s` of node `pc`."""
        if s.kind == "ret":
            v = self.subst(pc, s.post[10])
            if self.framed():
                return f"({v}, {self.subst(pc, s.mem)})"
            return v
        post = {r: self.subst(pc, e) for r, e in s.post.items()}
        if s.kind == "call":
            post = {10: f"{CALLEES[s.callee][1]} ({post[10]})"}
        vals = {}
        for r in self.live(s.succ):
            if r not in post:
                raise SystemExit(f"{s.name}: x{r} live at 0x{s.succ:x} but not carried")
            vals[r] = post[r]
        return self.napp(s.succ, self.subst(pc, s.mem), vals)

    def ndef(self, pc):
        ss = self.nodes[pc]
        ty = "BitVec 64 × Mem" if self.framed() else "BitVec 64"
        if len(ss) == 1:
            b = self.body(pc, ss[0])
        else:
            t = next(s for s in ss if s.guard[1])
            n = next(s for s in ss if not s.guard[1])
            b = (f"if {self.subst(pc, t.guard[0])} = true then\n    {self.body(pc, t)}\n"
                 f"  else\n    {self.body(pc, n)}")
        return (f"def {self.dn(pc)} {self.nargs(pc)} : {ty} :=\n  {b}\n")

    # ----------------------------------------------------------------------
    def lemma_binders(self, pc):
        vs = " ".join(f"v{r}" for r in self.live(pc))
        if self.inside(pc) and 1 in self.regs(pc):
            vs = (vs + " v1").strip()
        bv = f" ({vs} : BitVec 64)" if vs else ""
        if self.framed():
            hs = f"(hs : FnSp s {self.F}) (hr : r.toNat % 4 = 0) (hrod : RodataRead m)"
            if self.inside(pc):
                hs += f" (hra : bytesT8 m ({re.sub(r"\bv2\b", self.sp(self.entry), self.ra)}) = r)"
            return f"(m : Mem) (o : Array String) (s : Nat) (r : BitVec 64) (g : SFrame){bv}\n    {hs}"
        return f"(m : Mem) (o : Array String) (r : BitVec 64) (f : HFrame){bv}\n    (hr : r.toNat % 4 = 0)"

    def seg_app(self, pc, s, neg):
        args = ["_"] * (s.nvars + 2)
        for h, _ in s.hyps:
            if h.startswith("hg"):
                args.append("(fn_false hg)" if neg else "hg")
            elif h.startswith("htgt"):
                args.append("(by rw [fn_tgt hra hr]; exact hr)" if self.framed() and self.inside(pc)
                            else "(by rw [fn_tgt0 hr]; exact hr)")
            elif re.match(r"h(lo|hi|ht|win|al)_", h):
                args.append("(by kit_disch)")
            else:
                raise SystemExit(f"{s.name}: hypothesis {h}")
        return f"Lua.Vm.Arms.{s.name} {' '.join(args)}"

    def succ_app(self, pc):
        n = len(self.live(pc)) + (1 if self.inside(pc) and 1 in self.regs(pc) else 0)
        vs = " ".join(["_"] * n)
        if self.framed():
            hs = "hs hr (by fn_rod)" + (" (by fn_ra)" if self.inside(pc) else "")
            return f"{self.ln(pc)} _ _ s r g {vs} {hs}".replace("  ", " ")
        return f"{self.ln(pc)} _ _ r f {vs} hr".replace("  ", " ")

    def branch_proof(self, pc, s, neg, ind):
        I = " " * ind
        out = [f"{I}obtain ⟨_, acc, h⟩ := Vsa.Sim.SegSt.run acc h (by pins_of h)",
               f"{I}  ({self.seg_app(pc, s, neg)})"]
        unfold = f"rw [{self.dn(pc)}" + (", if_neg hg]" if neg else ", if_pos hg]" if s.guard else "]")
        if s.kind == "ret":
            if self.framed() and self.inside(pc):
                out.append(f"{I}rw [fn_sp_restore s ({self.pro_imm}#12) ({s.sp_imm}#12) (by decide)] at h")
                tgt = "fn_tgt hra hr"
            else:
                tgt = "fn_tgt0 hr"
            out.append(f"{I}refine ⟨_, acc, ?_⟩")
            out.append(f"{I}{unfold}")
            if self.framed():
                out.append(f"{I}dsimp only")
                out.append(f"{I}rw [memPatch_self]")
            out.append(f"{I}exact (h.at ({tgt})).repin (by pins_of h)")
            return out
        if s.kind == "call":
            summ = CALLEES[s.callee][0]
            out.append(f"{I}obtain ⟨_, acc, h⟩ := Vsa.Sim.SegSt.call acc h (by pins_of h)")
            out.append(f"{I}  ({summ} _ _ hframe? _ _ (by fn_rod) (by decide))")
        out.append(f"{I}obtain ⟨_, acc, h⟩ := Vsa.Sim.SegSt.run acc h (by pins_of h)")
        out.append(f"{I}  ({self.succ_app(s.succ)})")
        out.append(f"{I}refine ⟨_, acc, ?_⟩")
        out.append(f"{I}{unfold}")
        if s.mem != "m0":
            out.append(f"{I}simp (disch := kit_disch) only [memPatch_wm8_in] at h")
        out.append(f"{I}exact h")
        return out

    def lemma(self, pc):
        ss = self.nodes[pc]
        L = [(f"/-- **The summary**: the entry node's lemma, the lifted function `F`. -/\n" if pc == self.entry else "") + f"theorem {self.ln(pc)} {self.lemma_binders(pc)} :",
             f"    Triple (SegSt 0x{pc:08x}#64 {self.pins(pc)} (ArmPay m o))",
             f"      ({self.post(pc)}) := by",
             "  intro c h",
             "  have acc := Vsa.Machine.Steps.refl c"]
        if self.framed():
            L.append("  fn_sp_facts")
        if len(ss) == 1:
            L += self.branch_proof(pc, ss[0], False, 2)
        else:
            t = next(s for s in ss if s.guard[1])
            n = next(s for s in ss if not s.guard[1])
            L.append(f"  by_cases hg : {self.subst(pc, t.guard[0])} = true")
            b1 = self.branch_proof(pc, t, False, 4)
            b2 = self.branch_proof(pc, n, True, 4)
            L.append("  · " + b1[0].lstrip())
            L += b1[1:]
            L.append("  · " + b2[0].lstrip())
            L += b2[1:]
        return "\n".join(L) + "\n"

    # ----------------------------------------------------------------------
    def summary(self):
        return ""

    def files(self):
        """{path: text}: one module, or, past `CHUNK` nodes, the lifted
        functions (`<Mod>/Defs`), the node lemmas in chunks of `CHUNK`
        (`<Mod>/L<k>`, in proof order) and the summary (`<Mod>`), so that no
        module's elaboration holds more than `CHUNK` node proofs."""
        defs = "\n".join(self.ndef(pc) for pc in self.order)
        lems = [self.lemma(pc) for pc in self.order]
        nseg = len(self.segs)
        kind = (f"a {self.F}-byte frame below `sp`, the memory `memPatch`ed there"
                if self.framed() else "a leaf: the memory and the caller's frame kept")
        imports = "import Lua.Vm.Sim.Kit.Fn\n"
        if any(s.kind == "call" for s in self.segs):
            imports += "import Lua.Vm.Sim.Kit.Clzdi2\n"
        imports += f"import Lua.Vm.Arms.Segs.H{self.fn.lstrip('_')}\n"
        doc = (f"`{self.fn}` (entry `0x{self.entry:08x}`): its {nseg} generated segments\n"
               f"(`Lua/Vm/Arms/Segs/H{self.fn.lstrip('_')}.lean`) folded into {len(self.order)} nodes, {kind}.\n"
               "`N_<pc>` is the lifted function of the node at `pc`, `n_<pc>` its lemma; at the\n"
               "entry they are `F` (the lifted function level 2 relates to `F64`) and `sum` (the\n"
               "summary).")
        opens = ("open LeanRV64DExecutable LeanRV64DExecutable.Functions Sail ConcurrencyInterfaceV1 Vsa\n"
                 "open Vsa.Sim Vsa.Logic\nopen Lua.Vm.Sim\n")
        ns = f"Lua.Vm.Fn.{self.mod}"

        def module(imp, what, body):
            return (f"{imp}\n/-! {HEADER}\n\n{doc}\n\n{what}\n-/\n\n{opens}\n"
                    f"namespace {ns}\n\n{body}\nend {ns}\n")
        if len(self.order) <= CHUNK:
            return {OUT / f"{self.mod}.lean": module(
                imports, "This module: the whole fold.",
                defs + "\n" + "\n".join(lems) + "\n" + self.summary())}
        out = {OUT / self.mod / "Defs.lean": module(imports, "This module: the lifted functions.", defs)}
        prev = f"{ns}.Defs"
        chunks = [lems[k:k + CHUNK] for k in range(0, len(lems), CHUNK)]
        for k, ch in enumerate(chunks):
            out[OUT / self.mod / f"L{k}.lean"] = module(
                f"import {prev}\n", f"This module: node lemmas, chunk {k} of {len(chunks)}.",
                "\n".join(ch))
            prev = f"{ns}.L{k}"
        out[OUT / f"{self.mod}.lean"] = module(f"import {prev}\n", "This module: the index.", "")
        return out


CHUNK = 40


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--only", default="")
    a = ap.parse_args()
    drift = False
    for fn in ROUTINES:
        if a.only and fn not in a.only.split(","):
            continue
        f = Fn(fn)
        files = f.files()
        for path, t in files.items():
            if a.check:
                if not path.exists() or path.read_text() != t:
                    print(f"drift: {path.relative_to(ROOT)}")
                    drift = True
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(t)
        if not a.check:
            print(f"{fn}: {len(f.order)} nodes, {len(f.segs)} segments, {len(files)} modules")
    return 1 if drift else 0


if __name__ == "__main__":
    sys.exit(main())
