# lane float-sf4: a routine's jump tables, by the `jr`'s address: (the table's
# `.rodata` address, its entry count, the index register at the `jr` node).
# The node cases on the index (`hjt : idx.toNat < n`, from the predecessor's
# not-taken bound check `bltu n-1, idx`); entry `k`'s target is read off the
# ELF here and checked in Lean (`fn_jt_tgt`).
JUMPS = {"__divdf3": {0x8002ded4: (0x80054040, 16, 14), 0x8002df30: (0x80054080, 15, 14)}}
# a save slot's restore: `ld s<i>, off(sp)` as the segment states it
SV_RE = (r"\(sign_extend \(m := 64\) \(bytesT8 \(m0\) \(v2 \+ sign_extend \(m := 64\) "
         r"\((0x[0-9a-f]+)#12\)\)\.toNat : BitVec \(8 \* 8\)\)\)")


def jt_targets(tb, n):
    """The `n` targets of the jump table at `tb` (32-bit offsets from `tb`)."""
    rod = gli.sections(Path(gli.ELF).read_bytes())[".rodata"]
    out = []
    for k in range(n):
        o = tb + 4 * k - rod[0]
        out.append((tb + int.from_bytes(rod[1][o:o + 4], "little", signed=True)) % 2 ** 64)
    return out


def args_of(text):
    """The top-level parenthesised arguments of `f (a) (b) …` as strings."""
    out, depth, cur = [], 0, None
    for ch in text:
        if ch == "(":
            depth += 1
            if depth == 1:
                cur = []
                continue
        elif ch == ")":
            depth -= 1
            if depth == 0:
                out.append("".join(cur))
                cur = None
                continue
        if depth >= 1 and cur is not None:
            cur.append(ch)
    return out


def strip_wm4(text):
    """`bytesT8 (writeMap4 (m0) (A) (D)) x` -> `bytesT8 (m0) x` (lane float-sf6)."""
    key = "bytesT8 (writeMap4 (m0) "
    while key in text:
        i = text.index(key) + len("bytesT8 ")
        depth, j = 0, i
        while True:
            if text[j] == "(":
                depth += 1
            elif text[j] == ")":
                depth -= 1
                if depth == 0:
                    break
            j += 1
        text = text[:i] + "(m0)" + text[j + 1:]
    return text


def wm8_chain(mem):
    """`writeMap8 (writeMap8 (m0) (a1) (d1)) (a2) (d2)` -> [(a1, d1), (a2, d2)]."""
    stores = []
    while mem.startswith("writeMap8 ") or mem.startswith("writeMap4 "):
        inner, a, d = args_of(mem[len("writeMap8 "):])[:3]
        stores.insert(0, (a, d))
        mem = inner.strip()
    if mem != "m0":
        raise SystemExit(f"memory {mem[:60]}: not a writeMap8 chain over m0")
    return stores


class Seg:
    def __init__(self, name, lo, hi, spec):
        em = gen_segment.SegmentEmitter(spec)
        em.emit()
        self.name, self.lo, self.hi = name, lo, hi
        self.suf = name[21:]
        self.pre = [int(p["reg"][1:]) for p in spec["pins"]]
        self.post = {int(r[1:]): v for r, v in em.pins}
        self.end = em.end_pc
        self.mem = em.mem_expr or "m0"
        head = em.body_text.split(":= by")[0]
        m = re.search(r"^    \(([v\d ]+) : BitVec 64\)$", head, re.M)
        self.nvars = len(m.group(1).split()) if m else 0
        self.hyps = re.findall(r"^    \((h\w+) : (.*)\)$", head, re.M)
        lit = re.match(r"^\(?(0x[0-9a-f]+)#64\)?$", self.end)
        self.kind = "goto"
        self.succ = int(lit.group(1), 16) if lit else None
        if self.succ is None:
            self.kind = "ret"
        elif self.succ in CALLEES and self.post.get(1) != f"(0x{hi:08x}#64 : BitVec 64)" and \
                CUR_FN[0] in TAILS:
            # lane float-sf6: `j <callee>` (the frame popped, `ra` restored):
            # a tail node, the callee's summary its value and memory
            self.kind = "tail"
            self.callee = self.succ
            self.succ = None
        elif self.succ in CALLEES:
            self.kind = "call"
            self.callee = self.succ
            self.succ = hi
        elif not (gla_lo[0] <= self.succ < gla_lo[1]):
            raise SystemExit(f"{name}: jump out of the helper to 0x{self.succ:x}")
        self.guard = None
        for h, t in self.hyps:
            if h.startswith("hg"):
                g = re.match(r"^(.*) = (true|false)$", t)
                self.guard = (g.group(1), g.group(2) == "true")
        self.sp_delta = 0
        x2 = self.post.get(2, "v2")
        if x2 != "v2":
            m = re.match(r"^\(v2 \+ sign_extend \(m := 64\) \((0x[0-9a-f]+)#12\)\)$", x2)
            if not m:
                raise SystemExit(f"{name}: sp becomes {x2}")
            k = int(m.group(1), 16)
            self.sp_delta = k - 4096 if k >= 2048 else k
            self.sp_imm = m.group(1)


