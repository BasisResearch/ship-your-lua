def render_arm(op, specs, arms):
    lean_op, fname, kind = ARMS[op]
    idx, tgt, segs = chain(op, specs, arms)
    mods = sorted({f"Lua.Vm.Arms.Segs.{seg_module(n)}" for n, _, _ in segs})
    L = []
    L.append(f"""/-- **{lean_op}**: from the fetch head, the dispatch and the arm's segments
({', '.join(f'`{n}`' for n, _, _ in segs)}) return to the head in a state
related to the `Step`'s successor. -/
theorem sim_{lean_op} {{p : Proto}} ({"_hS" if kind == "jump" else "hS"} : Supported p) {{c : Config}} {{s s' : State}}
    (hR : VmRel p c s) {{ins : Word}} (hf : p.fetch s.pc = some ins)
    (hop : ins.op? = some .{lean_op}) (hstep : Step binaryHost p s s') :
    ∃ c' n, 0 < n ∧ StepsN n c c' ∧ VmRel p c' s' := by
  obtain ⟨w, hR⟩ := hR
  refine sim_of_run (w := w) ?_
{PRE[kind]}  have hnum : ins.opNum = {idx} := opNum_of_op? hop
  obtain ⟨c1, hs1, hlt1, hA⟩ := dispatch hR hf (by rw [hnum]; decide)
  have hc1 := hA.core
  have hr := hc1.ranges
  have hpc1 : c1.σ.regs.get? Register.PC = some (0x{tgt:08x}#64) := by
    rw [hA.pcAt, hnum]; exact congrArg some (by decide +kernel)
  have hTH : tohostAddr = 0x8005c6c0 := rfl
  have hbl := hr.base_lo
  have hbh := hr.base_hi
  have hba := hr.base_al
  have hcl := hr.ci_lo
  have hch := hr.ci_hi
  have hins := ins.isLt
  simp only [stackValueSize, ciSize] at hbh hch""")
    if kind != "jump":
        L.append("  simp only [Word.a, Word.b, Word.field] at htop ⊢")
    env = {r: v for r, (v, _) in CANON.items()}
    prev = None
    for k, (name, spec, em) in enumerate(segs, 1):
        cfg = f"c{k}"
        args, proofs = [], []
        for r in pin_regs(spec):
            if prev is None:
                args.append(env[r])
                proofs.append(CANON[r][1])
                continue
            pk, ppost, pvals = prev
            if pvals[r] == f"v{r[1:]}":
                args.append(env[r])
                proofs.append(get(ppost, r, pk))
            else:
                val, rw = NORM[r]
                L.append(f"""  have h{r}_{k} : {cfg}.σ.regs.get? Register.{r} = some {val} := by
    have h := {get(ppost, r, pk)}
    simp only [List.getElem_cons_succ, List.getElem_cons_zero] at h
    {rw}; exact h""")
                env[r] = val
                args.append(val)
                proofs.append(f"h{r}_{k}")
        pre_ok = "hpc1" if prev is None else f"hq{k - 1}.pcAt"
        good = "hc1.good" if prev is None else f"hq{k - 1}.good"
        rest = ("hc1.minstret, hc1.tick, ⟨hc1.text, rfl, rfl, hc1.ok⟩" if prev is None else
                f"hq{k - 1}.minstret, hq{k - 1}.tick, ⟨hq{k - 1}.armText, hq{k - 1}.armMem, "
                f"hq{k - 1}.armOut, hq{k - 1}.armOk⟩")
        hyps = " ".join(["(by arm_arith)"] * n_hyps(spec))
        L.append(f"  obtain ⟨c{k + 1}, hs{k + 1}, hq{k}⟩ := Arms.{name}\n    "
                 + "\n    ".join(wrap(args)) + "\n    c1.σ.mem c1.σ.sailOutput"
                 + (f"\n    {hyps}" if hyps else "")
                 + f"\n    {cfg} ⟨{good}, {pre_ok},\n      ⟨{', '.join(proofs)}, trivial⟩,"
                 f"\n      {rest}⟩")
        prev = (k, post_regs(em), {r: v for r, v in em.pins})
    k = len(segs)
    L.append(f"  have hsteps : Steps c1 c{k + 1} := "
             + (f"hs{k + 1}" if k == 1 else
                " ".join(f"(hs{i}.trans" for i in range(2, k + 1)) + f" hs{k + 1}" + ")" * (k - 1)))
    L.append(close(kind, prev[1], k).rstrip("\n"))
    body = "\n".join(L)
    imports = ["Lua.Vm.Sim.Dispatch", "Lua.Vm.Sim.Step"] + mods
    return fname, "\n".join(f"import {m}" for m in imports) + f"""

/-! {HEADER}

The A1 simulation lemma of `OP_{lean_op}` (kind `{kind}`). -/

open LeanRV64DExecutable LeanRV64DExecutable.Functions Sail ConcurrencyInterfaceV1 Vsa
open Vsa.Sim Vsa.Logic

namespace Lua.Vm.Sim

open Lua.Bytecode Lua.Vm.Layout
open Vsa.Machine (MState Config Steps StepsN)

{body}

end Lua.Vm.Sim
"""


def wrap(args):
    out, cur = [], ""
    for a in args:
        if cur and len(cur) + len(a) > 90:
            out.append(cur)
            cur = a
        else:
            cur = f"{cur} {a}".strip()
    if cur:
        out.append(cur)
    return out


_SEG_MOD = {}


def seg_module(name):
    if not _SEG_MOD:
        for f in (ROOT / "Lua/Vm/Arms/Segs").glob("G*.lean"):
            for m in re.finditer(r"^theorem (seg_\w+)", f.read_text(), re.M):
                _SEG_MOD[m.group(1)] = f.stem
    return _SEG_MOD[name]


