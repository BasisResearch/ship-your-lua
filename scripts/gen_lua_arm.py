#!/usr/bin/env python3
"""Emit the A1 simulation lemma of each pilot arm of luaV_execute.

For an opcode `OP`, `Lua/Vm/Sim/Arms/<Op>.lean` proves

    sim_<OP> : Supported p → VmRel p c s → p.fetch s.pc = some ins →
      ins.op? = some .<OP> → Step binaryHost p s s' →
      ∃ c' n, 0 < n ∧ StepsN n c c' ∧ VmRel p c' s'

by composing, with no instruction stepping of its own:

* the bytecode side: the opcode's kernel (`kernelAt`, one `simp`) and the
  combinator's inversion (`step_setR`, `step_jump`, `Lua/Vm/Sim/Step.lean`);
* the dispatch lemma (`dispatch`, `Lua/Vm/Sim/Dispatch.lean`) and the arm's
  target (`armTarget <n> = <addr>`, one kernel check);
* the arm's generated segment theorems (`Lua.Vm.Arms.seg_*`, chained from the
  arm target back to the fetch head), their register values given
  explicitly, their pins taken from the previous post by position
  (`pinsHold_get`), and every side condition `h*_<step>` discharged by
  `arm_arith` from the relation's `Ranges`;
* a close per kernel combinator (`copy`: `R[A] := R[B]`; `imm`: `R[A] :=`
  an immediate; `jump`), re-establishing the relation with `Core.write` /
  `Core.jump`.

The segment layouts (parameter order, post pin lists, side-condition
counts) are read from `scripts/gen_lua_arms.py`'s specs, so this file only
knows the relation's register interface and the three closes.

    python3 scripts/gen_lua_arm.py [--check]
"""
