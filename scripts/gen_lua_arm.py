def render():
    arms, specs, _ = gla.collect(set(ARMS) | set(ARMS2))
    files = {}
    for op in ARMS:
        fname, text = render_arm(op, specs, arms)
        files[OUT / f"{fname}.lean"] = text
    for op in ARMS2:
        fname, text = render_arm2(op, specs, arms)
        files[OUT / f"{fname}.lean"] = text
    files[ROOT / "Lua/Vm/Sim.lean"] = (
        "import Lua.Vm.Sim.Rel\nimport Lua.Vm.Sim.Dispatch\nimport Lua.Vm.Sim.Entry\n"
        + "".join(f"import Lua.Vm.Sim.Arms.{ARMS[op][1]}\n" for op in ARMS)
        + "".join(f"import Lua.Vm.Sim.Arms.{ARMS2[op][1]}\n" for op in ARMS2)
        + f"\n/-! {HEADER}\n\nA1: the relation `VmRel`, the entry lemma, the dispatch lemma, "
        "and the simulation lemmas of the arms with a proof (`Lua/Vm/Sim/Arms`). -/\n")
    return files


# Round 3 of abstraction discovery adopted the kit (Lua/Vm/Sim/Kit, abstractions/ROUND-3.md
# section 7) for every new A1 arm. This generator is frozen at the 25 arms of rounds 1-2.
FROZEN_ARMS = {"MOVE", "LOADI", "JMP", "ADD", "SUB", "ADDI", "ADDK", "SUBK", "BAND", "BOR",
               "BXOR", "EQI", "LTI", "GTI", "LEI", "GEI", "TEST", "TESTSET", "NOT", "BNOT",
               "LOADK", "LOADTRUE", "LOADFALSE", "LFALSESKIP", "FORLOOP"}


def main() -> int:
    new = {v[0] for v in ARMS.values()} - FROZEN_ARMS
    if new:
        print(f"gen_lua_arm.py is frozen (abstractions/ROUND-3.md section 7): prove {sorted(new)} on the kit, Lua/Vm/Sim/Kit", file=sys.stderr)
        return 1
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    files = render()
    if args.check:
        bad = [p for p, t in files.items() if not p.exists() or p.read_text() != t]
        for p in bad:
            print(f"drift: {p.relative_to(ROOT)}", file=sys.stderr)
        return 1 if bad else 0
    OUT.mkdir(parents=True, exist_ok=True)
    for p, t in files.items():
        p.write_text(t)
    print(f"wrote {len(files)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
