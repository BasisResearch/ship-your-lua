def targets():
    t = {}
    for r in csv.DictReader(open(gla.dfa.ARMS_TSV), delimiter="\t"):
        t[r["op"]] = (int(r["idx"]), int(r["target"], 16))
    return t


def chain(op, specs, arms):
    """The arm's segments in control-flow order, with their emitters."""
    names = dict(arms)[op]
    ems = {}
    for n in names:
        em = gen_segment.SegmentEmitter(specs[n][1])
        em.emit()
        ems[n] = em
    idx, tgt = targets()[op]
    out, pc = [], tgt
    while f"0x{pc:08x}" != HEAD:
        n = next(n for n in names if specs[n][0] == pc)
        out.append((n, specs[n][1], ems[n]))
        pc = int(re.match(r"\(?(0x[0-9a-f]+)#64", ems[n].end_pc).group(1), 16)
    return idx, tgt, out


def pin_regs(spec):
    return [p["reg"] for p in spec["pins"]]


def post_regs(em):
    return [r for r, _ in em.pins]


def n_hyps(spec):
    return sum(1 for p in spec["params"] if p.startswith("(h"))


def get(post, reg, k):
    return f"pinsHold_get hq{k}.pins {post.index(reg)} (by simp)"


