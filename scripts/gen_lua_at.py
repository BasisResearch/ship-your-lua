# the walk

class Arm:
    def __init__(self, op):
        self.op = op
        self.mod, self.target = ARMS[op]
        self.meta = seg_meta()
        self.segs = arm_segments(op)
        self.rows, self.logs = {}, {}
        self.lemmas = {}       # key -> (name, text)
        self.order = []
        self.fins = {}
        self.fsites = {}
        self.decls = []
        self.join_sides, self.join_pending, self.join_defs, self.join_st = {}, [], [], {}

    def fsite(self, mod, args, log, ret, frame, g=()):
        """The index of a soft-float call site's definitions (`f<k>`, its
        result; `k<k>`, a framed helper's memory; `f<k>_eq`, the result's
        specification), allocated once per (helper, arguments, log, return)."""
        key = (mod, args, log, ret, frame, g)
        if key not in self.fsites:
            self.logname(log)            # the result is over the call's entry memory
            self.fsites[key] = len(self.fsites)
            self.decls.append(("site", key))
        return self.fsites[key]

    def fsite_defs(self, only):
        out = []
        for (mod, args, log, ret, frame, g), k in self.fsites.items():
            if (mod, args, log, ret, frame, g) != only:
                continue
            xs = " ".join(f"(Loc.den X {lean_loc(y)})" for y in args)
            r = f"(0x{ret:x}#64)"
            if mod in PREMISE_FORM:
                h = PREMISED.get(mod)
                hyp = f"({h} : {mod}Spec) " if h else ""
                arg = h or PREMISE_PROOF[mod]
                out.append(f"/-- `{mod}` returning to `0x{ret:x}`: its result. -/\n"
                           f"noncomputable def f{k} (X : Cx) : BitVec 64 :=\n"
                           f"  Lua.Vm.Fn.{mod}.F (Log.den X {self.logname(log)}) X.w.sp {r} {xs}\n")
                out.append(f"/-- ... its frame. -/\n"
                           f"noncomputable def k{k} (X : Cx) (M : Mem) : Mem :=\n"
                           f"  Lua.Vm.Fn.{mod}.Fm M X.w.sp {r} {xs}\n")
                out.append(f"@[at_fspec] theorem f{k}_eq {hyp}(X : Cx) (hX : X.Ok) :\n"
                           f"    Lua.Num.F64.toModel (f{k} X) = Lua.Num.floor (Lua.Num.F64.toModel {xs}) :=\n"
                           f"  Lua.Vm.Fn.{mod}.spec {arg} _ _ _ _ (at_fnSp hX)\n")
            elif frame:
                out.append(f"/-- `{mod}` returning to `0x{ret:x}`: its result. -/\n"
                           f"def f{k} (X : Cx) : BitVec 64 :=\n"
                           f"  Lua.Vm.Fn.{mod}.F (Log.den X {self.logname(log)}) X.w.sp {r} {xs}\n")
                # lane F1-F6: a frame that stores the caller's saved registers
                # (`FRAME_G`) is over their row values (`frame4`)
                gs = (f"({FRAME_FN.get(mod, 'Lua.Vm.Sim.At.frame4')} "
                      + " ".join(f"(Loc.den X {lean_loc(y)})" for y in g) + ") ") if g else ""
                out.append(f"/-- ... its frame. -/\n"
                           f"def k{k} (X : Cx) (M : Mem) : Mem :=\n"
                           f"  Lua.Vm.Fn.{mod}.Fm M X.w.sp {r} {gs}{xs}\n")
                hsf, spec = (("", "spec_proved") if mod in FPROVED
                             else ("(hsf : SoftFloatSpec) ", "spec hsf"))
                out.append(f"@[at_fspec] theorem f{k}_eq {hsf}(X : Cx) (hX : X.Ok) :\n"
                           f"    f{k} X = Lua.Vm.Fn.{mod}.S {xs} :=\n"
                           f"  Lua.Vm.Fn.{mod}.{spec} _ _ _ {' '.join(['_'] * len(args))} (at_fnSp hX)"
                           + (" (by at_sext)" if mod == "Floatsidf" else "") + "\n")
            else:
                out.append(f"/-- `{mod}` returning to `0x{ret:x}`: its result. -/\n"
                           f"def f{k} (X : Cx) : BitVec 64 :=\n"
                           f"  Lua.Vm.Fn.{mod}.F {xs}\n")
                hsf, spec = (("", "spec_proved") if mod in FPROVED
                             else ("(hsf : SoftFloatSpec) ", "spec hsf"))
                out.append(f"@[at_fspec] theorem f{k}_eq {hsf}(X : Cx) :\n"
                           f"    f{k} X = Lua.Vm.Fn.{mod}.S {xs} :=\n"
                           f"  Lua.Vm.Fn.{mod}.{spec} {' '.join(['_'] * len(args))}\n")
        return "\n".join(out)

    def row(self, regs):
        key = tuple(sorted(regs.items()))
        if key == tuple(sorted(HEADROW.items())):
            return "headRow X"
        if key not in self.rows:
            self.rows[key] = f"r{len(self.rows)}"
        return f"{self.rows[key]} X"

    def logname(self, log):
        key = tuple(log)
        if not key:
            return "[]"
        if key not in self.logs:
            self.logs[key] = f"m{len(self.logs)}"
            self.decls.append(("log", key))
        return self.logs[key]

    def name(self, base, key):
        n, k = base, 0
        while n in {v[0] for kk, v in self.lemmas.items() if kk != key}:
            k += 1
            n = f"{base}_{k}"
        return n

    def bounds(self, st):
        """The slot and `K` bounds a lemma's side conditions use: the slots it
        touches, and the slots of the stores its loads are forwarded past."""
        bs = set(st.bounds)
        for _, t, a, _ in st.log:
            so = slot_of(t, a)
            if so:
                bs.add((so[0], so[1]))
        out = []
        for b in sorted(bs):
            if b == ("K",):
                out.append("(hK : X.ins.c < X.p.k.length)")
            else:
                out.append(f"(hs_{b[0]}{b[1]} : X.ins.{b[0]} + {b[1]} < X.p.maxstacksize)")
        return out

    def emit_seg(self, name, lo, st, st2, hi, guards):
        regs = {r: v for r, v in st.regs.items()}
        pre_row, pre_log = self.row(regs), self.logname(st.log)
        post_row, post_log = self.row(st2.regs), self.logname(st2.log)
        key = ("seg", name, pre_row, pre_log)
        if key in self.lemmas:
            return
        hyps = ["(X : Cx)", "(hX : X.Ok)"] + self.bounds(st2) + guards
        if ENV[0]:
            hyps += ENV_HYPS
        if st2.regs.get(27) == ("jmp",) and st.regs.get(27) != ("jmp",):
            hyps.append("(hj : (nextJump X.p X.s.pc).isSome = true)")   # `jmp_at`
        base = "at" + name[3:]
        lname = self.name(base, key)
        pre = "  have := jmp_lt hj\n" if any(h.startswith("(hj :") for h in hyps) else ""
        if ENV[0]:
            pre += "  at_env hE hb0\n"
        text = (f"theorem {lname} {' '.join(hyps)} :\n"
                f"    AtStep X 0x{lo:08x}#64 ({pre_row}) {pre_log} 0x{hi:08x}#64 ({post_row}) {post_log} := by\n"
                f"{pre}  at_seg Lua.Vm.Arms.{name}\n")
        self.lemmas[key] = (lname, text)
        self.order.append(key)

    def walk(self, pc, st, depth=0):
        """The emissions (thunks, in path order) of the paths from `pc` that
        reach the fetch head, or None."""
        if depth > 60:
            raise Stop("too deep")
        if pc == HEAD:
            return [lambda: self.emit_fin(st)]
        if pc in JOINS.get(self.op, {}) and pc not in st.joined:
            return self.join_arrive(pc, st)
        cands = [n for n in self.segs if int(n[4:12], 16) == pc]
        if not cands:
            raise Stop(f"no segment at 0x{pc:x}")
        out = None
        for name in cands:
            hi = int(name[13:21], 16)
            suf = name[21:]
            pre, post, guards = self.meta[name]
            st2 = st.copy()
            st2.bounds = set()
            try:
                for r in pre:
                    st2.get(r)
                guard = []
                nxt = hi
                callee = None
                for a, raw in code(pc, hi):
                    mnem = raw.split()[0]
                    if mnem in BRANCHES:
                        if a != hi - 4:
                            raise Stop("branch inside a segment")
                        head, rx, ry, tgt = branch(raw)
                        x, y = st2.get(rx), st2.get(ry)
                        taken = suf == "_t"
                        d = decide(head, x, y, st2.facts)
                        if d is not None and d != taken:
                            raise Stop("infeasible")
                        ground = decide(head, x, y, {}, f1=False) is not None
                        if head in ("==", "!="):
                            loc, v = (x, litval(y)) if litval(y) is not None else (y, litval(x))
                            if v is not None and litval(loc) is None:
                                eq = (head == "==") == taken
                                st2.facts[loc] = ("eq" if eq else "ne", v)
                        if not ground:
                            if len(guards) != 1:
                                raise Stop(f"guards {guards}")
                            guard.append(f"({guards[0]} : {guard_text(head, x, y, taken)})")
                            st2.path[a] = (guard_bool(head, x, y), taken)
                        nxt = tgt if taken else hi
                    elif mnem == "j":
                        nxt = int(ops_of(raw)[1][0], 16)
                    elif mnem == "jal":
                        callee = int(ops_of(raw)[1][0], 16)
                        st2.set(1, ("lit", a + 4))
                        nxt = callee
                    elif mnem == "auipc":
                        # a `.rodata` address: a constant's (`ld` next: the
                        # cell) or, before an error exit, the message's (lane
                        # F1-16: the exit's entry row keeps `a1`, `ErrIn`)
                        _, ao = ops_of(raw)
                        v = (imm(ao[1]) << 12) & 0xffffffff
                        v = v - (1 << 32) if v >> 31 else v
                        st2.set(ABI[ao[0]], ("lit", (a + v) & M64))
                    elif mnem in ("ret", "jr"):
                        raise Stop("return")
                    else:
                        step(st2, raw)
                # the row after the segment: the segment's post registers
                st2.regs = {r: v for r, v in st2.regs.items() if r in post and printable(v)}
                if callee in FCALLS and not FLOAT_ON[0]:
                    raise Stop(f"call to 0x{callee:x}")
                if (callee is not None and callee not in CALLS and callee not in ERRS
                        and callee not in FCALL_ARM.get(self.op, {})):
                    raise Stop(f"call to 0x{callee:x}")
                if callee in ERRS:
                    rest = []
                elif callee is not None:
                    rest = self.walk_call(callee, hi, st2, depth)
                else:
                    rest = self.walk(nxt, st2, depth + 1)
                if rest is None:
                    continue
                out = (out or []) + [lambda name=name, st=st, st2=st2, nxt=nxt, guard=guard:
                                     self.emit_seg(name, pc, st, st2, nxt, guard)] + rest
            except Stop as e:
                self.dropped.append((name, str(e)))
        return out

    def join_arrive(self, pc, st):
        """A side of the fork reaching the join `pc`: recorded, its join
        lemma emitted once the join row is known."""
        reg, fork = JOINS[self.op][pc]
        if fork not in st.path:
            raise Stop(f"join 0x{pc:x} off its fork")
        sides = self.join_sides.setdefault(pc, [])
        if not sides:
            self.join_pending.append(pc)
        sides.append(st)
        return [lambda: self.emit_join(pc, st)]

    def join_state(self, pc):
        """The join row: the registers both sides agree on, the joined
        register as `.fn j<k>`, the common log."""
        reg, fork = JOINS[self.op][pc]
        sides = self.join_sides[pc]
        pol = {s.path[fork][1]: s for s in sides}
        if len(sides) != 2 or set(pol) != {True, False}:
            raise Stop(f"join 0x{pc:x}: sides {len(sides)}")
        t, f = pol[True], pol[False]
        if t.path[fork][0] != f.path[fork][0] or tuple(t.log) != tuple(f.log):
            raise Stop(f"join 0x{pc:x}: the sides differ")
        k = len(self.join_defs)
        self.join_defs.append((t.path[fork][0], t.regs[reg], f.regs[reg], pc, fork, reg))
        self.decls.append(("join", k))
        regs = {r: v for r, v in t.regs.items() if r != reg and f.regs.get(r) == v}
        regs[reg] = ("join", k)
        st = State(regs, t.log, {l: v for l, v in t.facts.items() if f.facts.get(l) == v})
        st.path = {a: v for a, v in t.path.items() if a != fork and f.path.get(a) == v}
        st.joined = t.joined | {pc}
        self.join_st[pc] = (st, k)
        return st

    def joins_text(self):
        """The join pcs, for the hand side's cut (`at_walk`'s `at_cut`)."""
        if not self.join_st:
            return ""
        pcs = ", ".join(f"0x{pc:08x}" for pc in sorted(self.join_st))
        return (f"\n/-- The cut points (`JOINS`): the tail from each is proved once. -/\n"
                f"def joinPcs : List Nat := [{pcs}]\n")

    def join_def(self, k):
        g, vt, vf, pc, fork, reg = self.join_defs[k]
        return (f"/-- The cut at `0x{pc:x}`: `x{reg}` from the two sides of the fork at "
                f"`0x{fork:x}`. -/\n"
                f"@[at_fspec] def j{k} (X : Cx) : BitVec 64 :=\n"
                f"  if {g} then {den(vt)} else {den(vf)}\n")

    def emit_join(self, pc, st):
        jst, k = self.join_st[pc]
        reg, fork = JOINS[self.op][pc]
        g, taken = st.path[fork]
        pre_row, log = self.row(st.regs), self.logname(st.log)
        post_row = self.row(jst.regs)
        key = ("join", pc, pre_row, log)
        if key in self.lemmas:
            return
        lname = self.name(f"join_{pc:08x}", key)
        b = "true" if taken else "false"
        why = "if_pos hg" if taken else "if_neg (by simp only [hg, Bool.false_eq_true, not_false_eq_true])"
        text = (f"theorem {lname} (X : Cx) (hX : X.Ok) (hg : {g} = {b}) :\n"
                f"    AtStep X 0x{pc:08x}#64 ({pre_row}) {log} 0x{pc:08x}#64 ({post_row}) {log} := by\n"
                f"  at_join (show Loc.den X (.fn j{k}) = {den(st.regs[reg])} from {why})\n")
        self.lemmas[key] = (lname, text)
        self.order.append(key)

    def walk_call(self, entry, ret, st, depth):
        callee = CALLS.get(entry)
        if entry in FCALL_ARM.get(self.op, {}):
            callee = f"fcall_{FCALL_ARM[self.op][entry][0]}"
        post, hyps, proof, _ = call_effect(st, callee, ret)
        nxt = ret
        if callee in OBSERVED:
            # run on through the observing segment at `ret`
            obs = [n for n in self.segs if int(n[4:12], 16) == ret]
            if len(obs) != 1:
                raise Stop(f"observer at 0x{ret:x}: {obs}")
            name = obs[0]
            ins = code(ret, int(name[13:21], 16))
            mnem = ins[0][1].split()[0]
            if mnem not in OBSERVED[callee] or len(ins) != 2 or ins[1][1].split()[0] != "j":
                raise Stop(f"observer {ins}")
            kind, lemma = OBSERVED[callee][mnem]
            post.set(10, (kind,) + post.obs)
            nxt = int(ops_of(ins[1][1])[1][0], 16)
            _, opost, _ = self.meta[name]
            post.regs = {r: v for r, v in post.regs.items() if r in opost}
            proof = proof.replace("{obs_seg}", f"Lua.Vm.Arms.{name}").replace(
                "{obs_lemma}", f"Lua.Vm.Sim.At.{lemma}")
        post.regs = {r: v for r, v in post.regs.items() if printable(v)}
        rest = self.walk(nxt, post, depth + 1)
        if rest is None:
            return None
        return [lambda: self.emit_call(entry, ret, st, post, hyps, proof, nxt)] + rest

    def emit_call(self, entry, ret, st, post, hyps, proof, nxt=None):
        nxt = ret if nxt is None else nxt
        pre_row, pre_log = self.row(st.regs), self.logname(st.log)
        post_row, post_log = self.row(post.regs), self.logname(post.log)
        key = ("call", entry, ret, pre_row, pre_log)
        if key not in self.lemmas:
            hyps = [h.replace("{log}", pre_log) for h in hyps]
            hs = ["(X : Cx)", "(hX : X.Ok)"] + self.bounds(post) + hyps
            if ENV[0]:
                hs += ENV_HYPS
            lname = self.name(f"call_{ret:08x}", key)
            text = (f"theorem {lname} {' '.join(hs)} :\n"
                    f"    AtStep X 0x{entry:08x}#64 ({pre_row}) {pre_log} 0x{nxt:08x}#64 ({post_row}) {post_log} := by\n"
                    f"  {proof}\n")
            self.lemmas[key] = (lname, text)
            self.order.append(key)

    def emit_fin(self, st):
        row, log = self.row(st.regs), self.logname(st.log)
        key = ("fin", row, log)
        if key in self.lemmas:
            return
        x27 = st.regs.get(27)
        t = to_aff(x27) if x27 != ("jmp",) and x27[0] != "back" else None
        back = []
        if x27 == ("jmp",):
            pc_txt = "jmpPc X"
        elif x27[0] == "back":
            pc_txt = f"X.s.pc + {x27[1]} - X.ins.bx"
            back = [f"(hbx : X.ins.bx ≤ X.s.pc + {x27[1]})"]
        else:
            if t is None or t[0].get("code") != 1 or t[0].get("pc") != 4 or (t[1] % 4):
                raise Stop(f"head pc {x27}")
            extra = {a: c for a, c in t[0].items() if a not in ("code", "pc")}
            if any(c % 4 for c in extra.values()):
                raise Stop("head pc")
            pc_txt = " + ".join(["X.s.pc"] + [f"{c // 4} * X.ins.{a}" if c != 4 else f"X.ins.{a}"
                                               for a, c in extra.items()] + [str(t[1] // 4)])
        # the stored slots: the newest tag (`sb` at +8) and payload (`sd` at +0)
        slots, bounds = {}, set()
        for kind, t, a, v in st.log:
            if kind == "clob":
                continue
            so = slot_of(t, a)
            if so is None:
                continue
            f, k, o = so
            e = slots.setdefault((f, k), {})
            if kind == "sb" and o == 8:
                e.setdefault("t", v)
            elif kind == "sd" and o == 0:
                e.setdefault("v", v)
            else:
                raise Stop("a partial slot store")
            bounds.add((f, k))
        ws = []
        for (f, k), e in sorted(slots.items()):
            if FLOAT_ON[0] and set(e) == {"v"}:
                e["t"] = ("tag", f, k)     # `chgfltvalue`: the entry's tag kept
            if set(e) != {"t", "v"}:
                raise Stop("a slot with its tag or payload unstored")
            ws.append(f"⟨.{f}, {k}, {lean_loc(e['t'])}, {lean_loc(e['v'])}⟩")
        st.bounds = bounds
        hs = ["(X : Cx)", "(hX : X.Ok)"] + self.bounds(st) + back
        lname = self.name("fin", key)
        outer = any(kind == "clob" and t == () for kind, t, a, v in st.log)
        text = (f"theorem {lname} {' '.join(hs)} {{c : Config}}\n"
                f"    (h : At X 0x{HEAD:08x}#64 ({row}) {log} c) :\n"
                f"    {'AtFinE' if outer else 'AtFin'} X {log} [{', '.join(ws)}] ({pc_txt}) c := by\n"
                f"  {'at_finE' if outer else 'at_fin'}\n")
        if len(ws) > 2 and outer:
            raise Stop("an outer store with more than two stored slots")
        if len(ws) > 2:
            # round 5: many stored slots: the frame and keep facts (log-only)
            # each in a declaration of its own (`at_fin_with`)
            bs = self.bounds(st)
            args = " ".join(["X", "hX"] + [re.match(r"\((\w+) :", b).group(1) for b in bs])
            wl = f"([{', '.join(ws)}] : List SlotW)"
            text = (f"theorem {lname}_frame {' '.join(['(X : Cx)', '(hX : X.Ok)'] + bs)} :\n"
                    f"    ∀ x, ¬ Slots X.p X.w x → ¬ Scratch X.w x → ¬ CFrame X.w x →\n"
                    f"      (Log.den X {log})[x]? = X.c.σ.mem[x]? := by\n"
                    f"  at_facts hX; try at_unfold\n  at_fin_frame\n\n"
                    f"theorem {lname}_keep {' '.join(['(X : Cx)', '(hX : X.Ok)'] + bs)} :\n"
                    f"    ∀ x, Slots X.p X.w x → (∀ e ∈ {wl}, x < X.w.slot (e.j X) ∨\n"
                    f"      X.w.slot (e.j X) + 16 ≤ x) → (Log.den X {log})[x]? = X.c.σ.mem[x]? := by\n"
                    f"  at_facts hX; try at_unfold\n  at_fin_keep\n\n"
                    f"theorem {lname} {' '.join(hs)} {{c : Config}}\n"
                    f"    (h : At X 0x{HEAD:08x}#64 ({row}) {log} c) :\n"
                    f"    AtFin X {log} [{', '.join(ws)}] ({pc_txt}) c := by\n"
                    f"  at_fin_with ({lname}_frame {args}), ({lname}_keep {args})\n")
        self.lemmas[key] = (lname, text)
        self.order.append(key)

    def run(self):
        PRUNE_FLOAT[0] = self.op in PRUNE_ARMS
        ENV[0] = self.op in ENV_ARMS
        FLOAT_ON[0] = self.op in FLOAT_ARMS
        CUR[0] = self
        self.dropped = []
        st = State(HEADROW, [], {loc: ("eq", VNUMFLT_) for loc in FLOAT_SEED.get(self.op, [])})
        thunks = self.walk(self.target, st) or []
        while self.join_pending:
            pc = self.join_pending.pop(0)
            thunks += self.walk(pc, self.join_state(pc)) or []
        for f in thunks:
            f()

