#!/usr/bin/env python3
"""Emit the at-lemmas of an F1 arm: its generated segments restated between
location-list rows, each proved in its own declaration (round-4 bake-off,
B-SEGLOCAL; `Lua/Vm/Sim/Kit/At.lean`).

For an arm (`ARMS` below: the opcode, its jump-table target) the arm's
paths are walked from the target over the generated segments
(`Lua/Vm/Arms/arms.tsv`, the theorems in `Lua/Vm/Arms/Segs/*.lean`), with a
symbolic state: every register's `Loc` (an affine address over the context's
pointers and instruction fields, a slot's or `K[C]`'s tag or payload in the
entry memory, an operation over locations) and the path's stores (an `Ent`
log over the entry memory). A load is resolved against the log by region
(the regions of `At.lean`'s `rgnOf`): a store in another region is skipped,
the same address returns the stored location, an overlap stops the walk. A
branch whose operands are known (constants, or a location the path already
compared with a constant) takes one polarity. A path ends at the fetch head
or at the entry of an error exit (`ERRS`: `luaG_runerror`, …, which do not
return), or is dropped at a call that is not summarised (the float helpers).

For each (segment, entry row) visited one at-lemma is emitted:

    theorem at_<lo>_<hi>[_t|_n][_<k>] (X : Cx) (hX : X.Ok) (bounds) (guards) :
        AtStep X <lo> <row> <log> <hi'> <row'> <log'> := by at_seg <segment>

its guards stated over the locations (`hg_<step>`, the segment's own names),
for every summarised call one `call_<site>[_<k>]` (the helper's summary at
the row, `at_call`), and for every arrival at the fetch head one
`fin_<k>` (the close's facts: `AtFin`). The rows and logs are `@[at_row]`
abbreviations, so consecutive lemmas meet syntactically.

Output (GENERATED, `--check` reports drift):
    Lua/Vm/At/<Op>.lean

    python3 scripts/gen_lua_at.py [--check] [--only OP_FORPREP]
"""
