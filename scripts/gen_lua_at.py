def call_effect(st, callee, ret):
    """The state after a summarised call, and the at-lemma's extra hypotheses
    and proof."""
    if callee in FCALLS_BY_NAME:
        a0 = a1 = None          # the soft-float calls read their arguments below
    else:
        a0, a1 = st.get(10), st.get(11)
    dead = [r for r in FRAME if r not in st.regs]
    if not set(dead) <= {22, 26}:
        raise Stop(f"frame registers {dead} unknown")
    post = State({r: st.get(r) for r in FRAME if r not in dead}, st.log, st.facts)
    pins = [f"Vsa.Sim.SegSt.pin{r}" for r in dead]
    post.bounds = set()
    hyps, pre_regs = [], [10, 11, 1] + FRAME
    if callee in FCALLS_BY_NAME:
        mod, nargs, frame = FCALLS_BY_NAME[callee]
        args = tuple(st.get(10 + i) for i in range(nargs))
        g = ()
        if mod in FRAME_G:
            g = tuple(st.get(r) for r in FRAME_G[mod][1])
            if any(x is None for x in g):
                raise Stop(f"{mod}: a stored frame register unknown")
        k = CUR[0].fsite(mod, args, tuple(st.log), ret, frame, g)
        post.set(10, ("fsite", k))
        vs = " ".join(["_"] * nargs)
        pre = (f"{PREMISED[mod]} " if mod in PREMISED else
               f"{PREMISE_PROOF[mod]} " if mod in PREMISE_PROOF else "")
        if mod in PREMISED:
            hyps.append(f"({PREMISED[mod]} : {mod}Spec)")
        if frame:
            pre_log = CUR[0].logname(tuple(st.log))
            post.log.insert(0, ("clob", (("sp", 1),), -frame, (frame, k)))
            if mod in FOUTER:
                # lane F1-F7: the store outside the frame, the same memory
                # function over the call's entry memory
                oa, on = FOUTER[mod]
                post.log.insert(0, ("clob", (), oa, (on, f"fun X _ => k{k} X (Log.den X {pre_log})")))
            sm = FRAME_G[mod][0] if mod in FRAME_G else f"Lua.Vm.Fn.{mod}.sum"
            proof = (f"at_call [{{pins}}] ({sm} {pre}_ _ _ _ sframe? {vs} {FSP.get(mod, '(at_fnSp hX)')} "
                     f"(by decide) (by at_rod){FARGS.get(mod, '')})")
        else:
            proof = f"at_call [{{pins}}] (Lua.Vm.Fn.{mod}.sum _ _ _ hframe? {vs} (by decide))"
    elif callee == "__moddi3":
        post.set(10, ("srem", a0, a1))
        hyps.append(f"(hn : {den(a1)} ≠ 0#64)")
        proof = ("at_call [{pins}] (Lua.Vm.Sim.Kit.moddi3_sum _ _ _ hframe? _ _ "
                 "(by at_unfold at hn; exact hn) (by decide))")
    elif callee == "__divdi3":
        post.set(10, ("sdiv", a0, a1))
        hyps.append(f"(hn : {den(a1)} ≠ 0#64)")
        proof = ("at_call [{pins}] (Lua.Vm.Sim.Kit.divdi3_sum _ _ _ hframe? _ _ "
                 "(by at_unfold at hn; exact hn) (by decide))")
    elif callee == "__hidden___udivdi3":
        post.set(10, ("udiv", a0, a1))
        post.set(11, ("umod", a0, a1))
        hyps.append(f"(hn : {den(a1)} ≠ 0#64)")
        pins = ["Vsa.Sim.SegSt.pin5"] + pins
        proof = ("at_call [{pins}] (Lua.Vm.Sim.Kit.udivdi3_sum _ _ _ _ hframe? _ _ "
                 "(by at_unfold at hn; exact hn) (by decide))")
    elif callee == "l_strcmp":
        # `lstr_sum`: two string registers' payloads; the return memory is
        # the prologue's six saves (`lsMem`)
        sa, sb = a0, a1
        if sa[0] != "val" or sb[0] != "val":
            raise Stop("l_strcmp of a non-slot")
        post = State({r: st.get(r) for r in FRAME if r not in (22, 26)}, st.log, st.facts)
        post.bounds = {(sa[1], sa[2]), (sb[1], sb[2])}
        sp = (("sp", 1),)
        for off, r in ((-16, 8), (-8, 1), (-24, 9), (-32, 18), (-40, 19), (-48, 20)):
            post.store("sd", sp, off, st.get(r))
        hyps.append("(x y : List UInt8)")
        hyps.append(f"(hsa : X.s.regs (X.ins.{sa[1]} + {sa[2]}) = some (.str x))")
        hyps.append(f"(hsb : X.s.regs (X.ins.{sb[1]} + {sb[2]}) = some (.str y))")
        post.obs = (sa[1], sb[1])
        proof = "at_lstr {obs_seg} {obs_lemma}"
        return post, hyps, "at_open\n  " + proof, pre_regs
    elif callee == "luaV_equalobj" and CUR[0].op in ("OP_EQ_F", "OP_EQK_F"):
        # lane F1-F4: `equalobj_flt_sum` (a float among the two values): the
        # answer `Value.rawEq` as 0/1; the callee frames `[sp - 160, sp)` a
        # `clob` with content `eqfMem`
        k = CUR[0].op == "OP_EQK_F"
        a2 = st.get(12)
        want = ((("lit", 0), aff({"base": 1, "a": 16}), aff({"k": 1, "b": 16})) if k else
                (("L",), aff({"base": 1, "a": 16}), aff({"base": 1, "b": 16})))
        if (a0, a1, a2) != want:
            raise Stop(f"luaV_equalobj of {a0}, {a1}, {a2}")
        post = State({r: st.get(r) for r in FRAME if r not in (22, 26)}, st.log, st.facts)
        post.bounds = {("a", 0)} if k else {("a", 0), ("b", 0)}
        n2 = "(X.w.k + stackValueSize * X.ins.b)" if k else "(X.w.slot (X.ins.b + 0))"
        post.log.insert(0, ("clob", (("sp", 1),), -160,
                            (160, f"fun X M => Lua.Vm.Sim.Kit.eqfMem 0x{ret:x}#64 (Loc.den X .L) "
                                  f"(X.w.slot (X.ins.a + 0)) {n2} X.w.sp M")))
        post.set(10, ("eqf", "k" if k else "b"))
        hyps += ["(va vb : Value)", "(hsa : X.s.regs (X.ins.a + 0) = some va)",
                 "(hky : kval X.p X.ins.b = some vb)" if k else "(hsb : X.s.regs (X.ins.b + 0) = some vb)",
                 "(hfab : ¬ (va.NotFlt ∧ vb.NotFlt))"]
        post.path, post.joined = dict(st.path), st.joined
        return post, hyps, "at_open\n  " + ("at_eqkf" if k else "at_eqf"), pre_regs
    elif callee == "luaV_equalobj":
        # `lngeq_sum`: `luaV_equalobj(NULL, R[A], K[B])` on two long strings;
        # the return memory is the entry's with `ra` saved at `sp - 8`
        a2 = st.get(12)
        if a0 != ("lit", 0) or a1 != aff({"base": 1, "a": 16}) or a2 != aff({"k": 1, "b": 16}):
            raise Stop(f"luaV_equalobj of {a0}, {a1}, {a2}")
        if st.log:
            raise Stop("luaV_equalobj after stores")
        post = State({r: st.get(r) for r in FRAME if r not in (22, 26)}, st.log, st.facts)
        post.bounds = {("a", 0)}
        post.store("sd", (("sp", 1),), -8, ("lit", ret))
        post.set(10, ("streqk",))
        hyps += ["(x y : List UInt8)", "(hsa : X.s.regs (X.ins.a + 0) = some (.str x))",
                 "(hky : kval X.p X.ins.b = some (.str y))",
                 "(hta : slotTag X.c.σ.mem (X.w.slot (X.ins.a + 0)) = 84#8)",
                 "(htk : slotTag X.c.σ.mem (X.w.k + stackValueSize * X.ins.b) = 84#8)"]
        return post, hyps, "at_open\n  at_eqk", pre_regs
    elif callee == "luaV_objlen":
        # `len_sum`: `luaV_objlen(L, R[A], R[B])` on a string `R[B]`; the
        # return memory: `ra` saved at `sp - 8`, then `R[A]` the integer `#R[B]`
        a2 = st.get(12)
        sa, sb = aff({"base": 1, "a": 16}), aff({"base": 1, "b": 16})
        if a0 != ("L",) or a1 != sa or a2 != sb:
            raise Stop(f"luaV_objlen of {a0}, {a1}, {a2}")
        post = State({r: st.get(r) for r in FRAME if r not in (22, 26)}, st.log, st.facts)
        post.bounds = {("a", 0), ("b", 0)}
        post.store("sd", (("sp", 1),), -8, ("lit", ret))
        post.store("sb", sa[1], 8, ("lit", 3))
        post.store("sd", sa[1], 0, ("slen", "b"))
        hyps += ["(y : List UInt8)", "(hsb : X.s.regs (X.ins.b + 0) = some (.str y))"]
        return post, hyps, "at_open\n  at_objlen", pre_regs
    elif callee == "luaH_getshortstr":
        # `gss_at`: `luaH_getshortstr(_ENV's table, K[C])` finds `print`'s
        # node; the memory is unchanged
        if a0 != aff({"tab": 1}) or a1 != ("kval",):
            raise Stop(f"luaH_getshortstr of {a0}, {a1}")
        post.set(10, aff({"pn": 1}))
        hyps.append("(hkc : kval X.p X.ins.c = some (.str printKey))")
        proof = ("at_call [{pins}] (Lua.Vm.Sim.At.gss_at hX hE (by simpa only [Word.c, Word.field, Nat.shiftRight_eq_div_pow] using hkc) (by at_logwin) _ (by decide) hframe?)")
    elif callee == "luaV_tointeger":
        s = to_aff(a0)
        if s is None or not slot_of(tuple(sorted(s[0].items(), key=lambda y: ATOMS.index(y[0]))), s[1]):
            raise Stop("luaV_tointeger of a non-slot")
        terms = tuple(sorted(s[0].items(), key=lambda y: ATOMS.index(y[0])))
        f, k, _ = slot_of(terms, s[1])
        q = to_aff(a1)
        qt = tuple(sorted(q[0].items(), key=lambda y: ATOMS.index(y[0])))
        hyps.append(f"(ht : slotTag X.c.σ.mem (X.w.slot (X.ins.{f} + {k})) = 3#8)")
        sp = (("sp", 1),)
        post.store("sd", sp, -24, st.get(9))
        post.store("sd", sp, -8, st.get(1))
        post.store("sd", qt, q[1], post.load(terms, s[1], 8))
        post.set(10, ("lit", 1))
        proof = ("at_call [{pins}] (Lua.Vm.Sim.Kit.toint_sum _ _ X.w.sp _ _ hframe? _ _ "
                 "(by constructor <;> first | decide | kit_disch) (by rfl) (by at_pre ht))")
    else:
        raise Stop(f"no summary for {callee}")
    proof = "\n  ".join(["at_open"] + [f"obtain ⟨_, h⟩ := {p} h" for p in pins] +
                          [proof.replace("[{pins}] ", "")])
    post.path, post.joined = dict(st.path), st.joined
    return post, hyps, proof, pre_regs


