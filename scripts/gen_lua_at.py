def seg_meta():
    """{name: (pre registers, post registers, guard names)} from the Segs files."""
    meta = {}
    for f in sorted(SEGS.glob("*.lean")):
        text = f.read_text()
        for m in re.finditer(r"^theorem (seg_\w+)\n(.*?):= by", text, re.S | re.M):
            name, body = m.group(1), m.group(2)
            tri = body[body.index(": Triple"):]
            pre_l = tri[tri.index("[") + 1:tri.index("]")]
            post_s = tri[tri.index("(SegSt", tri.index("]")):]
            post_l = post_s[post_s.index("[") + 1:]
            pre = [int(r) for r in re.findall(r"⟨Register\.x(\d+),", pre_l)]
            depth, end = 0, 0
            for i, ch in enumerate(post_l):
                if ch == "[":
                    depth += 1
                elif ch == "]":
                    if depth == 0:
                        end = i
                        break
                    depth -= 1
            post = [int(r) for r in re.findall(r"⟨Register\.x(\d+),", post_l[:end])]
            guards = re.findall(r"\((hg_\d+) :", body)
            meta[name] = (pre, post, guards)
    return meta


def arm_segments(op):
    for r in csv.DictReader((ln for ln in open(ARMS_TSV) if not ln.startswith("#")), delimiter="\t"):
        if r["op"] == op:
            return r["segments"].split()
    raise SystemExit(f"no arm {op}")


def code(lo, hi):
    return [(a, raw) for a, _, raw in
            d2s.disassemble(d2s.DEFAULT_OBJDUMP, d2s.DEFAULT_ELF, lo, hi)]


