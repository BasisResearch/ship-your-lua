# locations

def aff(terms, add=0):
    """A canonical affine location: terms {atom: coef}, a signed constant."""
    t = tuple(sorted(((a, c) for a, c in terms.items() if c), key=lambda x: ATOMS.index(x[0])))
    return ("aff", t, add)


def to_aff(x):
    k = x[0]
    if k == "aff":
        return dict(x[1]), x[2]
    if k in ("sp", "L", "ci", "base"):
        return {k: 1}, 0
    if k == "pc":
        return {"code": 1, "pc": 4}, 4 * x[1]
    if k == "lit" and x[1] < 2 ** 32:
        return {}, x[1]
    return None


def canon(x):
    """An affine location in its fetch-head form where it is one."""
    if x[0] != "aff":
        return x
    t, add = dict(x[1]), x[2]
    if add == 0 and len(t) == 1:
        (a, c), = t.items()
        if c == 1 and a in ("sp", "L", "ci", "base"):
            return (a,)
    if t == {"code": 1, "pc": 4} and add % 4 == 0 and add >= 0:
        return ("pc", add // 4)
    if not t and add >= 0:
        return ("lit", add)
    return x


def aff_add(x, y_terms, y_add):
    t, add = x
    t = dict(t)
    for a, c in y_terms.items():
        t[a] = t.get(a, 0) + c
    return canon(aff(t, add + y_add))


def litval(x):
    if x[0] == "lit":
        return x[1]
    if x[0] == "litn":
        return x[2]
    return None


def lean_aff(terms, add):
    ts = ", ".join(f"({c}, .{a})" for a, c in terms)
    return f"⟨[{ts}], {max(add, 0)}, {max(-add, 0)}⟩"


# locations whose value is stated over the context `X` (`Kit/AtCond.lean`): printed as
# `.lit <term over X>`, so they may stand in a row (an abbreviation over `X`) but not in a log
XLOCS = ("andi", "kbit", "jmp", "strle", "strlt", "streqk")


def lean_loc(x):
    k = x[0]
    if k == "andi":   # `andi` of an unknown value: closed over the context
        return f"(.lit ((Loc.den X {lean_loc(x[1])}) &&& (Loc.den X {lean_loc(x[2])})))"
    if k == "kbit":
        return "(.lit (if X.ins.k then 1#64 else 0#64))"
    if k == "jmp":
        return "(.lit (BitVec.ofNat 64 (X.w.code + 4 * jmpPc X)))"
    if k == "strle":
        return f"(.lit (if !lexLt (sOf X .{x[2]}) (sOf X .{x[1]}) then 1#64 else 0#64))"
    if k == "slen":
        # closed over the context: a log may hold it (`Loc.fn`)
        return f"(.fn fun X => BitVec.ofNat 64 (sOf X .{x[1]}).length)"
    if k == "streqk":
        return "(.lit (if sOf X .a = kOf X then 1#64 else 0#64))"
    if k == "strlt":
        return f"(.lit (if lexLt (sOf X .{x[1]}) (sOf X .{x[2]}) then 1#64 else 0#64))"
    if k == "lit":
        return f"(.lit 0x{x[1]:x}#64)"
    if k == "litn":
        return f"(.lit (BitVec.ofNat 64 {x[1]}))"
    if k in ("sp", "L", "ci", "base", "insw", "ktag", "kval"):
        return f".{k}"
    if k == "pc":
        return f"(.pc {x[1]})"
    if k == "aff":
        return f"(.nat {lean_aff(x[1], x[2])})"
    if k in ("tag", "val"):
        return f"(.{k} .{x[1]} {x[2]})"
    if k == "cell":
        return f"(.cell {lean_aff(x[1], x[2])})"
    if k == "cell1":
        return f"(.cell1 {lean_aff(x[1], x[2])})"
    if k in ("add", "sub", "xor", "srem", "sdiv", "udiv", "umod", "and", "or", "sll", "srl",
             "addw", "subw"):
        return f"(.{k} {lean_loc(x[1])} {lean_loc(x[2])})"
    if k == "snez":
        return f"(.snez {lean_loc(x[1])})"
    raise Stop(f"no location for {x}")


def den(x):
    return f"(Loc.den X {lean_loc(x)})"


# --------------------------------------------------------------------------
# regions (as `At.lean`'s `rgnOf`)

def region(terms):
    t = dict(terms)
    if "k" in t:
        return "kArr"
    if "base" in t:
        return "slots"
    if "ci" in t:
        return "savedpc"
    if "L" in t:
        return "ltop"
    if "sp" in t:
        return "sp"
    return None


def slot_of(terms, add):
    """`(field, k, off)` of a slot address `base + 16·field + add`."""
    t = dict(terms)
    if t.get("base") != 1 or len(t) != 2:
        return None
    (f, c), = [(a, c) for a, c in t.items() if a != "base"]
    if f not in ("a", "b", "c") or c != 16 or add < 0:
        return None
    return f, add // 16, add % 16


def walk_loc(x):
    """`x` and its sub-locations."""
    yield x
    if isinstance(x, tuple):
        for y in x[1:]:
            if isinstance(y, tuple) and y and isinstance(y[0], str):
                yield from walk_loc(y)


class State:
    def __init__(self, regs, log, facts):
        self.regs = dict(regs)
        self.log = list(log)        # newest first: (kind, terms, add, loc)
        self.facts = dict(facts)    # loc -> ("eq"|"ne", value)
        self.bounds = set()         # slots / K touched: ("a", k) or ("K",)

    def copy(self):
        s = State(self.regs, self.log, self.facts)
        s.bounds = set(self.bounds)
        return s

    def get(self, r):
        if r == 0:
            return ("lit", 0)
        if r not in self.regs:
            raise Stop(f"x{r} unknown")
        return self.regs[r]

    def set(self, r, v):
        if r != 0:
            self.regs[r] = v

    def touch(self, terms, add):
        s = slot_of(terms, add)
        if s:
            self.bounds.add((s[0], s[1]))
        if dict(terms).get("k"):
            self.bounds.add(("K",))

    def load(self, terms, add, size):
        self.touch(terms, add)
        rg = region(terms)
        for kind, t2, a2, v in self.log:
            sz2 = 8 if kind == "sd" else 1
            if region(t2) != rg:
                continue
            if t2 != terms:
                if rg == "slots" and dict(t2).get("base") and dict(terms).get("base"):
                    raise Stop("slot load against a store at another field")
                continue
            if add == a2 and size == sz2:
                if kind == "sb":
                    lv = litval(v)
                    if lv is None:
                        raise Stop("byte load of a symbolic byte store")
                    return ("lit", lv & 0xff)
                return v
            if add + size <= a2 or a2 + sz2 <= add:
                continue
            raise Stop("partial overlap")
        # the entry memory
        s = slot_of(terms, add)
        if s and size == 1 and s[2] == 8:
            return ("tag", s[0], s[1])
        if s and size == 8 and s[2] == 0:
            return ("val", s[0], s[1])
        t = dict(terms)
        if ENV[0] and len(t) == 1 and list(t.values()) == [1]:
            a = list(t)[0]
            if (a, add, size) in ENV_LOADS:
                return ENV_LOADS[(a, add, size)]
        if t == {"k": 1, "c": 16} and size == 1 and add == 8:
            return ("ktag",)
        if t == {"k": 1, "c": 16} and size == 8 and add == 0:
            return ("kval",)
        if t == {"sp": 1} and add == 0 and size == 8:
            return canon(aff({"k": 1}))
        if t == {"ci": 1} and add == 40 and size == 4:
            return ("lit", 0)                 # `ci->u.l.trap` (`trap_ld`)
        if t == {"code": 1, "pc": 4} and add == 4 and size == 4:
            return ("w4n",)                   # the following `OP_JMP` (`jmp_at`)
        if size == 8:
            return ("cell", terms, add)
        raise Stop(f"byte load at {terms}+{add}")

    def store(self, kind, terms, add, v):
        if any(isinstance(x, tuple) and x and x[0] in XLOCS for x in walk_loc(v)):
            raise Stop("a store of a location over the context")
        self.touch(terms, add)
        self.log.insert(0, (kind, terms, add, v))


# --------------------------------------------------------------------------
# the instructions

def ops_of(raw):
    mnem, _, rest = raw.partition(" ")
    rest = rest.split("#")[0].split("<")[0].strip()
    return mnem, [o.strip() for o in rest.split(",") if o.strip()]


def mem_operand(o):
    m = re.match(r"(-?\d+)\((\w+)\)", o)
    return int(m.group(1)), ABI[m.group(2)]


def imm(o):
    return int(o, 0)


def addr_of(st, base, off):
    a = to_aff(st.get(base))
    if a is None:
        raise Stop(f"address from {st.get(base)}")
    t, add = a
    return aff(t)[1], add + off


def step(st, raw):
    """One non-control instruction on the symbolic state."""
    mnem, o = ops_of(raw)
    R = lambda s: ABI[s]    # noqa: E731
    if mnem in ("ld", "lbu", "lw"):
        off, b = mem_operand(o[1])
        terms, add = addr_of(st, b, off)
        st.set(R(o[0]), st.load(terms, add, {"ld": 8, "lbu": 1, "lw": 4}[mnem]))
    elif mnem == "lui":
        v = (imm(o[1]) << 12) & 0xffffffff
        st.set(R(o[0]), ("lit", (v | (M64 ^ 0xffffffff)) if v >> 31 else v))
    elif mnem == "sext.w":
        x = st.get(R(o[1]))
        if litval(x) is None:
            raise Stop("sext.w of a symbolic value")
        v = litval(x) & 0xffffffff
        st.set(R(o[0]), ("lit", (v | (M64 ^ 0xffffffff)) if v >> 31 else v))
    elif mnem == "andi":
        x, k = st.get(R(o[1])), imm(o[2]) & M64
        if x == aff({"bx": 1}) and k == 1:
            st.set(R(o[0]), ("kbit",))        # `docondjump`'s k (`kraw_eq`)
        elif litval(x) is not None:
            st.set(R(o[0]), ("lit", litval(x) & k))
        else:
            st.set(R(o[0]), ("andi", x, ("lit", k)))
    elif mnem in ("sd", "sb"):
        off, b = mem_operand(o[1])
        terms, add = addr_of(st, b, off)
        st.store(mnem, terms, add, st.get(R(o[0])))
    elif mnem == "li":
        st.set(R(o[0]), ("lit", imm(o[1]) & M64))
    elif mnem == "auipc":
        # a pc-relative address (an error message): not kept in the row
        st.set(R(o[0]), ("opaque",))
    elif mnem == "mv":
        st.set(R(o[0]), st.get(R(o[1])))
    elif mnem == "addi":
        x = st.get(R(o[1]))
        a = to_aff(x)
        if a is not None and x[0] != "lit":
            st.set(R(o[0]), aff_add(a, {}, imm(o[2])))
        elif litval(x) is not None:
            st.set(R(o[0]), ("lit", (litval(x) + imm(o[2])) & M64))
        else:
            st.set(R(o[0]), ("add", x, ("lit", imm(o[2]) & M64)))
    elif mnem == "add":
        x, y = st.get(R(o[1])), st.get(R(o[2]))
        ax, ay = to_aff(x), to_aff(y)
        if x == ("pc", 1) and y == ("shl", ("add", ("nsj",), ("lit", 0xffffffffff000002)), 2):
            st.set(R(o[0]), ("jmp",))         # `donextjump`'s target (`jmp_at`)
        elif ax is not None and ay is not None and not (x[0] == "lit" and y[0] == "lit"):
            st.set(R(o[0]), aff_add(ax, ay[0], ay[1]))
        else:
            st.set(R(o[0]), ("add", x, y))
    elif mnem == "sub":
        st.set(R(o[0]), ("sub", st.get(R(o[1])), st.get(R(o[2]))))
    elif mnem == "neg":
        st.set(R(o[0]), ("sub", ("lit", 0), st.get(R(o[1]))))
    elif mnem == "xor":
        st.set(R(o[0]), ("xor", st.get(R(o[1])), st.get(R(o[2]))))
    elif mnem in ("and", "or", "sll", "srl", "subw"):
        st.set(R(o[0]), (mnem, st.get(R(o[1])), st.get(R(o[2]))))
    elif mnem == "negw":
        st.set(R(o[0]), ("subw", ("lit", 0), st.get(R(o[1]))))
    elif mnem == "addiw":
        st.set(R(o[0]), ("addw", st.get(R(o[1])), ("lit", imm(o[2]) & M64)))
    elif mnem == "snez":
        st.set(R(o[0]), ("snez", st.get(R(o[1]))))
    elif mnem == "slli":
        x, k = st.get(R(o[1])), imm(o[2])
        if litval(x) is not None:
            st.set(R(o[0]), ("lit", (litval(x) << k) & M64))
        elif x[0] == "aff" and x[2] == 0 and len(x[1]) == 1:
            (a, c), = x[1]
            st.set(R(o[0]), aff({a: c << k}))
        elif x[0] == "add":
            st.set(R(o[0]), ("shl", x, k))
        else:
            raise Stop(f"slli of {x}")
    elif mnem == "srli":
        x, k = st.get(R(o[1])), imm(o[2])
        if litval(x) is None:
            raise Stop("srli of a symbolic value")
        st.set(R(o[0]), ("lit", litval(x) >> k))
    elif mnem == "srliw":
        x, k = st.get(R(o[1])), imm(o[2])
        if x == ("w4n",) and k == 7:
            st.set(R(o[0]), ("nsj",))
            return
        if x != ("insw",):
            raise Stop("srliw of a non-instruction")
        st.set(R(o[0]), {24: aff({"c": 1}), 15: aff({"bx": 1})}.get(k, ("shr", k)))
    elif mnem == "zext.b":
        x = st.get(R(o[1]))
        if x == ("shr", 16) and ENV[0]:
            st.set(R(o[0]), ("lit", 0))      # `B = 0` (`hb0`): upvalue 0
        elif x == ("shr", 7):
            st.set(R(o[0]), aff({"a": 1}))
        elif x == ("shr", 16):
            st.set(R(o[0]), aff({"b": 1}))
        elif litval(x) is not None:
            st.set(R(o[0]), ("lit", litval(x) & 0xff))
        else:
            raise Stop(f"zext.b of {x}")
    else:
        raise Stop(f"instruction {raw}")


# the branches: mnemonic -> (Lean guard head, operand order, comparison)
def branch(raw):
    mnem, o = ops_of(raw)
    tgt = int(o[-1], 16)
    z = "zero"
    table = {"beq": ("==", o[0], o[1]), "bne": ("!=", o[0], o[1]),
             "beqz": ("==", o[0], z), "bnez": ("!=", o[0], z),
             "blt": ("zopz0zI_s", o[0], o[1]), "bge": ("zopz0zKzJ_s", o[0], o[1]),
             "bltu": ("zopz0zI_u", o[0], o[1]), "bgeu": ("zopz0zKzJ_u", o[0], o[1]),
             "bltz": ("zopz0zI_s", o[0], z), "bgez": ("zopz0zKzJ_s", o[0], z),
             "blez": ("zopz0zKzJ_s", z, o[0]), "bgtz": ("zopz0zI_s", z, o[0])}
    head, a, b = table[mnem]
    return head, ABI[a], ABI[b], tgt


