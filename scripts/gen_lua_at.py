# the instructions

def ops_of(raw):
    mnem, _, rest = raw.partition(" ")
    rest = rest.split("#")[0].split("<")[0].strip()
    return mnem, [o.strip() for o in rest.split(",") if o.strip()]


def mem_operand(o):
    m = re.match(r"(-?\d+)\((\w+)\)", o)
    return int(m.group(1)), ABI[m.group(2)]


def imm(o):
    return int(o, 0)


def addr_of(st, base, off):
    a = to_aff(st.get(base))
    if a is None:
        raise Stop(f"address from {st.get(base)}")
    t, add = a
    return aff(t)[1], add + off


def step(st, raw):
    """One non-control instruction on the symbolic state."""
    mnem, o = ops_of(raw)
    R = lambda s: ABI[s]    # noqa: E731
    if mnem in ("ld", "lbu", "lw"):
        off, b = mem_operand(o[1])
        terms, add = addr_of(st, b, off)
        st.set(R(o[0]), st.load(terms, add, {"ld": 8, "lbu": 1, "lw": 4}[mnem]))
    elif mnem == "lui":
        v = (imm(o[1]) << 12) & 0xffffffff
        st.set(R(o[0]), ("lit", (v | (M64 ^ 0xffffffff)) if v >> 31 else v))
    elif mnem == "sext.w":
        x = st.get(R(o[1]))
        if litval(x) is None and FLOAT_ON[0]:
            st.set(R(o[0]), ("addw", x, ("lit", 0)))     # `addiw rd, rs, 0`
            return
        if litval(x) is None:
            raise Stop("sext.w of a symbolic value")
        v = litval(x) & 0xffffffff
        st.set(R(o[0]), ("lit", (v | (M64 ^ 0xffffffff)) if v >> 31 else v))
    elif mnem == "andi":
        x, k = st.get(R(o[1])), imm(o[2]) & M64
        if x == aff({"bx": 1}) and k == 1:
            st.set(R(o[0]), ("kbit",))        # `docondjump`'s k (`kraw_eq`)
        elif litval(x) is not None:
            st.set(R(o[0]), ("lit", litval(x) & k))
        else:
            st.set(R(o[0]), ("andi", x, ("lit", k)))
    elif mnem in ("sd", "sb"):
        off, b = mem_operand(o[1])
        terms, add = addr_of(st, b, off)
        st.store(mnem, terms, add, st.get(R(o[0])))
    elif mnem == "li":
        st.set(R(o[0]), ("lit", imm(o[1]) & M64))
    elif mnem == "auipc":
        # a pc-relative address (an error message): not kept in the row
        st.set(R(o[0]), ("opaque",))
    elif mnem == "mv":
        st.set(R(o[0]), st.get(R(o[1])))
    elif mnem == "addi":
        x = st.get(R(o[1]))
        a = to_aff(x)
        if a is not None and x[0] != "lit":
            st.set(R(o[0]), aff_add(a, {}, imm(o[2])))
        elif litval(x) is not None:
            st.set(R(o[0]), ("lit", (litval(x) + imm(o[2])) & M64))
        else:
            st.set(R(o[0]), ("add", x, ("lit", imm(o[2]) & M64)))
    elif mnem == "add":
        x, y = st.get(R(o[1])), st.get(R(o[2]))
        ax, ay = to_aff(x), to_aff(y)
        if x == ("pc", 1) and y == ("shl", ("add", ("nsj",), ("lit", 0xffffffffff000002)), 2):
            st.set(R(o[0]), ("jmp",))         # `donextjump`'s target (`jmp_at`)
        elif ax is not None and ay is not None and not (x[0] == "lit" and y[0] == "lit"):
            st.set(R(o[0]), aff_add(ax, ay[0], ay[1]))
        else:
            st.set(R(o[0]), ("add", x, y))
    elif mnem == "addw" and FLOAT_ON[0]:
        st.set(R(o[0]), ("addwr", st.get(R(o[1])), st.get(R(o[2]))))
    elif mnem == "sub":
        x, y = st.get(R(o[1])), st.get(R(o[2]))
        if FLOAT_ON[0] and x[0] == "pc" and y[0] == "aff" and dict(y[1]) == {"bx": 4} and y[2] == 0:
            st.set(R(o[0]), ("back", x[1]))      # `pc += 1 - Bx` (`FORLOOP`'s jump back)
        else:
            st.set(R(o[0]), ("sub", x, y))
    elif mnem == "neg":
        st.set(R(o[0]), ("sub", ("lit", 0), st.get(R(o[1]))))
    elif mnem == "xor":
        st.set(R(o[0]), ("xor", st.get(R(o[1])), st.get(R(o[2]))))
    elif mnem in ("and", "or", "sll", "srl", "subw"):
        st.set(R(o[0]), (mnem, st.get(R(o[1])), st.get(R(o[2]))))
    elif mnem == "negw":
        st.set(R(o[0]), ("subw", ("lit", 0), st.get(R(o[1]))))
    elif mnem == "addiw":
        st.set(R(o[0]), ("addw", st.get(R(o[1])), ("lit", imm(o[2]) & M64)))
    elif mnem == "snez":
        st.set(R(o[0]), ("snez", st.get(R(o[1]))))
    elif mnem in ("seqz", "slti", "sltiu", "slt", "sltu", "not") and not FLOAT_ON[0]:
        raise Stop(f"instruction {raw}")
    elif mnem == "seqz":
        st.set(R(o[0]), ("sltu", st.get(R(o[1])), ("lit", 1)))
    elif mnem in ("slti", "sltiu"):
        st.set(R(o[0]), ("slt" if mnem == "slti" else "sltu", st.get(R(o[1])), ("lit", imm(o[2]) & M64)))
    elif mnem in ("slt", "sltu"):
        st.set(R(o[0]), (mnem, st.get(R(o[1])), st.get(R(o[2]))))
    elif mnem == "sgtz" and FLOAT_ON[0]:     # round 5: `__gedf2`'s `> 0` idiom
        st.set(R(o[0]), ("slt", ("lit", 0), st.get(R(o[1]))))
    elif mnem == "not":
        st.set(R(o[0]), ("xor", st.get(R(o[1])), ("lit", M64)))
    elif mnem == "xori" and FLOAT_ON[0]:     # lane F2: `LEintfloat`'s `!(fi < i)`
        st.set(R(o[0]), ("xor", st.get(R(o[1])), ("lit", imm(o[2]) & M64)))
    elif mnem == "slli":
        x, k = st.get(R(o[1])), imm(o[2])
        if litval(x) is not None:
            st.set(R(o[0]), ("lit", (litval(x) << k) & M64))
        elif x[0] == "aff" and x[2] == 0 and len(x[1]) == 1:
            (a, c), = x[1]
            st.set(R(o[0]), aff({a: c << k}))
        elif x[0] == "add":
            st.set(R(o[0]), ("shl", x, k))
        else:
            raise Stop(f"slli of {x}")
    elif mnem == "srli":
        x, k = st.get(R(o[1])), imm(o[2])
        if litval(x) is None:
            if not FLOAT_ON[0]:
                raise Stop("srli of a symbolic value")
            st.set(R(o[0]), ("srl", x, ("lit", k)))
        else:
            st.set(R(o[0]), ("lit", litval(x) >> k))
    elif mnem == "srliw":
        x, k = st.get(R(o[1])), imm(o[2])
        if x == ("w4n",) and k == 7:
            st.set(R(o[0]), ("nsj",))
            return
        if x != ("insw",):
            raise Stop("srliw of a non-instruction")
        st.set(R(o[0]), {24: aff({"c": 1}), 15: aff({"bx": 1})}.get(k, ("shr", k)))
    elif mnem == "zext.b":
        x = st.get(R(o[1]))
        if x == ("shr", 16) and ENV[0]:
            st.set(R(o[0]), ("lit", 0))      # `B = 0` (`hb0`): upvalue 0
        elif x == ("shr", 7):
            st.set(R(o[0]), aff({"a": 1}))
        elif x == ("shr", 16):
            st.set(R(o[0]), aff({"b": 1}))
        elif litval(x) is not None:
            st.set(R(o[0]), ("lit", litval(x) & 0xff))
        else:
            raise Stop(f"zext.b of {x}")
    else:
        raise Stop(f"instruction {raw}")


# the branches: mnemonic -> (Lean guard head, operand order, comparison)
def branch(raw):
    mnem, o = ops_of(raw)
    tgt = int(o[-1], 16)
    z = "zero"
    table = {"beq": ("==", o[0], o[1]), "bne": ("!=", o[0], o[1]),
             "beqz": ("==", o[0], z), "bnez": ("!=", o[0], z),
             "blt": ("zopz0zI_s", o[0], o[1]), "bge": ("zopz0zKzJ_s", o[0], o[1]),
             "bltu": ("zopz0zI_u", o[0], o[1]), "bgeu": ("zopz0zKzJ_u", o[0], o[1]),
             "bltz": ("zopz0zI_s", o[0], z), "bgez": ("zopz0zKzJ_s", o[0], z),
             "blez": ("zopz0zKzJ_s", z, o[0]), "bgtz": ("zopz0zI_s", z, o[0])}
    head, a, b = table[mnem]
    return head, ABI[a], ABI[b], tgt


BRANCHES = {"beq", "bne", "beqz", "bnez", "blt", "bge", "bltu", "bgeu", "bltz", "bgez",
            "blez", "bgtz"}


def sgn(v):
    return v - (1 << 64) if v >> 63 else v


VNUMFLT = 19     # LUA_VNUMFLT: no F1 value has it (`ValRepr.ne_float`)
# the arms whose float paths are pruned (the earlier arms keep their files)
PRUNE_ARMS = {"OP_UNM", "OP_SHL", "OP_SHR", "OP_SHLI", "OP_SHRI", "OP_BANDK", "OP_BORK",
              "OP_BXORK"}
PRUNE_FLOAT = [False]


def decide(head, x, y, facts, f1=True):
    """The branch's value when the operands decide it, else None. With `f1`,
    a tag is never the float tag: the float paths are infeasible (the arm
    closes the not-taken guard from `ValRepr.ne_float`)."""
    if litval(x) is None and litval(y) is None:
        if facts.get(y, ("", None))[0] == "eq":
            y = ("lit", facts[y][1])
        elif facts.get(x, ("", None))[0] == "eq":
            x = ("lit", facts[x][1])
    vx, vy = litval(x), litval(y)
    if vx is not None and vy is not None:
        return {"==": vx == vy, "!=": vx != vy, "zopz0zI_s": sgn(vx) < sgn(vy),
                "zopz0zKzJ_s": sgn(vx) >= sgn(vy), "zopz0zI_u": vx < vy,
                "zopz0zKzJ_u": vx >= vy}[head]
    if head in ("==", "!="):
        loc, v = (x, vy) if vy is not None else (y, vx) if vx is not None else (None, None)
        if f1 and PRUNE_FLOAT[0] and loc is not None and loc[0] in ("tag", "ktag") and v == VNUMFLT:
            return head == "!="
        if loc is not None and loc in facts:
            rel, w = facts[loc]
            eq = (w == v) if rel == "eq" else (False if w == v else None)
            if eq is not None:
                return eq if head == "==" else not eq
    return None


def guard_bool(head, x, y):
    """A branch's condition as a `Bool` over the locations."""
    if head in ("==", "!="):
        return f"({den(x)} {head} {den(y)})"
    return f"({head} {den(x)} {den(y)})"


def guard_text(head, x, y, val):
    b = "true" if val else "false"
    if head in ("==", "!="):
        return f"({den(x)} {head} {den(y)}) = {b}"
    return f"{head} {den(x)} {den(y)} = {b}"


