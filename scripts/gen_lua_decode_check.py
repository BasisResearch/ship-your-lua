#!/usr/bin/env python3
"""Kernel check that the generic decoder `Vsa.Sim.decodeW`
(`Vsa/Sim/DecodeNF.lean`, the `#simp_nf` normal form of `ext_decode`) covers
every instruction word of `luaV_execute` in `c/lua-riscv-htif.elf`.

For each unique word `w` of luaV_execute (its range from
experiments/census/luaV_execute_arms.json) it emits

    example : (ext_decode 0x<w>#32).run σ = .ok (<ast>) σ :=
      Vsa.Sim.decodeW σ hmisa hpriv hsec

where `<ast>` is what the Lean evaluator decodes the word to
(`scripts/lua_decode_ast_dump.lean`, committed as `ast_dump.txt`), so each
example checks both that `decodeW`'s autoParam `rfl` finds the instruction
and that it is the evaluator's. Modules hold `PART` words.

This replaces a per-word decode table (one `simp` proof per word, the
approach of the copied `Vsa/Sim/DecodeTable/*`): with `decodeW`, a decode
fact for any word is `Vsa.Sim.decodeW (w := 0x<w>#32) σ h1 h2 h3`, so no
per-word lemma is needed.

    python3 scripts/gen_lua_decode_check.py --dump   # needs lake: rewrites ast_dump.txt
    python3 scripts/gen_lua_decode_check.py [--check]
"""
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ELF = ROOT / "c/lua-riscv-htif.elf"
OUT = ROOT / "Lua/Vm/DecodeCheck"
DUMP = OUT / "ast_dump.txt"
OBJDUMP = os.environ.get("OBJDUMP") or str(
    Path.home() / "toolchains/xpack-riscv-none-elf-gcc-15.2.0-1/bin/riscv-none-elf-objdump")
import json  # noqa: E402
_S = json.load(open(ROOT / "experiments/census/luaV_execute_arms.json"))["summary"]["luaV_execute"]
EXEC_LO, EXEC_HI = int(_S["start"], 16), int(_S["end"], 16)
PART = 128
INST_RE = re.compile(r"^\s+([0-9a-f]+):\s+([0-9a-f]{8})\s")


def exec_words() -> tuple[int, list[str]]:
    out = subprocess.run([OBJDUMP, "-d", str(ELF),
                          f"--start-address=0x{EXEC_LO:x}",
                          f"--stop-address=0x{EXEC_HI:x}"],
                         capture_output=True, text=True, check=True).stdout
    ws = [m.group(2) for m in map(INST_RE.match, out.splitlines())
          if m and EXEC_LO <= int(m.group(1), 16) < EXEC_HI]
    assert len(ws) == (EXEC_HI - EXEC_LO) // 4, len(ws)
    return len(ws), sorted(set(ws))


def cmd_dump():
    _, words = exec_words()
    with tempfile.NamedTemporaryFile("w", suffix=".txt", delete=False) as f:
        f.write("\n".join(words) + "\n")
        tmp = f.name
    res = subprocess.run(["lake", "env", "lean", "--run",
                          "scripts/lua_decode_ast_dump.lean", str(ELF), tmp],
                         cwd=ROOT, capture_output=True, text=True)
    os.unlink(tmp)
    lines = [l for l in res.stdout.splitlines() if re.match(r"^[0-9a-f]{8};", l)]
    if res.returncode != 0 or len(lines) != len(words) or \
            any(";OK;" not in l for l in lines):
        sys.exit(f"error: dump failed: {res.stderr[-2000:]}")
    OUT.mkdir(parents=True, exist_ok=True)
    DUMP.write_text("\n".join(" ".join(l.split()) for l in lines) + "\n")
    print(f"wrote {DUMP} ({len(lines)} words)")


HEADER = '''import Vsa.Sim.DecodeNF

/-! GENERATED by scripts/gen_lua_decode_check.py -- do not edit.

`Vsa.Sim.decodeW` decodes words {first}..{last} of `luaV_execute` (part
{p}/{n}) to the instruction the Lean evaluator gives. -/

open LeanRV64DExecutable LeanRV64DExecutable.Functions Sail ConcurrencyInterfaceV1 Vsa
open Register

namespace Lua.Vm.DecodeCheck

variable (σ : SequentialState RegisterType trivialChoiceSource)
    (hmisa : σ.regs.get? Register.misa =
      some ((Vsa.Sim.initMisa) : RegisterType Register.misa))
    (hpriv : σ.regs.get? Register.cur_privilege =
      some (Privilege.Machine : RegisterType Register.cur_privilege))
    (hsec : σ.regs.get? Register.mseccfg =
      some ((0#64) : RegisterType Register.mseccfg))

'''


def render() -> dict:
    ninsts, words = exec_words()
    asts = {}
    for line in DUMP.read_text().splitlines():
        w, _, ast = line.split(";", 2)
        asts[w] = ast
    if sorted(asts) != words:
        sys.exit("error: ast_dump.txt is not luaV_execute's word set; rerun --dump")
    parts = [words[i:i + PART] for i in range(0, len(words), PART)]
    files, mods = {}, []
    for p, ch in enumerate(parts, 1):
        body = HEADER.format(first=ch[0], last=ch[-1], p=p, n=len(parts))
        for w in ch:
            body += (f"example : (ext_decode 0x{w}#32).run σ =\n"
                     f"    .ok ({asts[w]}) σ :=\n"
                     f"  Vsa.Sim.decodeW σ hmisa hpriv hsec\n\n")
        body += "end Lua.Vm.DecodeCheck\n"
        files[OUT / f"P{p:02d}.lean"] = body
        mods.append(f"Lua.Vm.DecodeCheck.P{p:02d}")
    top = "".join(f"import {m}\n" for m in mods)
    top += ("\n/-! GENERATED by scripts/gen_lua_decode_check.py -- do not edit.\n\n"
            f"`Vsa.Sim.decodeW` covers all {len(words)} unique words of the "
            f"{ninsts} instructions of\n`luaV_execute`: one kernel-checked "
            "`example` per word, in the modules above. -/\n")
    files[ROOT / "Lua/Vm/DecodeCheck.lean"] = top
    return files


def main():
    if "--dump" in sys.argv:
        return cmd_dump()
    files = render()
    if "--check" in sys.argv:
        stale = [p for p, t in files.items() if not p.exists() or p.read_text() != t]
        stale += [p for p in OUT.glob("*.lean") if p not in files]
        if stale:
            print("decode check: DRIFT", *[str(p.relative_to(ROOT)) for p in stale])
            sys.exit(1)
        print(f"decode check: ok ({len(files)} files)")
        return
    for p, t in files.items():
        if not p.exists() or p.read_text() != t:
            p.write_text(t)
    for p in OUT.glob("*.lean"):
        if p not in files:
            p.unlink()
    print(f"wrote {len(files)} files")


if __name__ == "__main__":
    main()
