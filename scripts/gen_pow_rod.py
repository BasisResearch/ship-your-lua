#!/usr/bin/env python3
"""`.rodata` words of libm `pow`'s lifted functions, one lemma per address
(lane float-sf7).

The level-(b) walk (`Lua/Vm/Fn/PowLens.lean`, `pw_rod`) rewrites a value
function's `.rodata` load `bytesT8 m a` to its word. Deciding `rodQ a = v`
in the kernel costs about a second per address (the image's pages), so each
address the routines read is decided once here, by `decide +kernel` in a
declaration of its own, and `pw_rod` applies `rod_<hex>` by name.

The addresses are read off the generated lifted functions (`auipc` + `ld`:
`((pc + (imm20 << 12)) + imm12).toNat`), the words off `Lua/Vm/Image.lean`'s
pages (the ELF's bytes).

Output (GENERATED, `--check` reports drift):
    Lua/Vm/Fn/PowRod.lean

    python3 scripts/gen_pow_rod.py [--check]
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "Lua/Vm/Fn/PowRod.lean"
HEADER = "GENERATED by scripts/gen_pow_rod.py -- do not edit."
SOURCES = ["Lua/Vm/Fn/Ieee754Pow/Defs.lean", "Lua/Vm/Fn/Scalbn.lean", "Lua/Vm/Fn/MathOflow.lean",
           "Lua/Vm/Fn/MathUflow.lean", "Lua/Vm/Fn/Xflow.lean", "Lua/Vm/Fn/WithErrno.lean"]
LOAD = re.compile(r"\(\(\(0x([0-9a-f]+)#64\) \+ sign_extend \(m := 64\) \(\(0x([0-9a-f]+)#20\) \+\+\+ "
                  r"0x000#12\)\) \+ sign_extend \(m := 64\) \(0x([0-9a-f]+)#12\)\)\.toNat")


def sext(v, bits):
    return v - (1 << bits) if v >> (bits - 1) else v


def image():
    text = (ROOT / "Lua/Vm/Image.lean").read_text()
    pages = {int(n): int(v, 16) for n, v in re.findall(r"def rodataPage(\d+) : Nat := 0x([0-9a-f]+)", text)}
    base = int(re.search(r"def rodataBase : Nat := 0x([0-9a-f]+)", text).group(1), 16)
    return pages, base


def word(pages, base, a):
    v = 0
    for i in range(8):
        off = a - base + i
        b = (pages[off // 256] >> (8 * (off % 256))) & 0xff
        v |= b << (8 * i)
    return v


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    addrs = set()
    for src in SOURCES:
        for pc, hi, lo in LOAD.findall((ROOT / src).read_text()):
            addrs.add((int(pc, 16) + sext(int(hi, 16), 20) * 4096 + sext(int(lo, 16), 12)) % 2 ** 64)
    pages, base = image()
    body = []
    for ad in sorted(addrs):
        v = word(pages, base, ad)
        body.append(f"theorem rod_{ad:x} : Lua.Vm.Fn.Ieee754Sqrt.rodQ {ad} = 0x{v:016x}#64 := by\n"
                    f"  decide +kernel\n")
    text = ("import Lua.Vm.Fn.SqrtSpec\n\n"
            f"/-! {HEADER}\n\nThe `.rodata` words libm `pow`'s lifted functions load, each decided once\n"
            "(`pw_rod`, `Lua/Vm/Fn/PowLens.lean`, applies `rod_<hex>` by name).\n-/\n\n"
            "namespace Lua.Vm.Fn.PowRod\n\n" + "\n".join(body) + "\nend Lua.Vm.Fn.PowRod\n")
    if a.check:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"drift: {OUT.relative_to(ROOT)}")
            return 1
        return 0
    OUT.write_text(text)
    print(f"{len(addrs)} addresses")
    return 0


if __name__ == "__main__":
    sys.exit(main())
