#!/usr/bin/env python3
"""Generate Lua/Bytecode/OpCode.lean from vendor/lua-5.4.7/src/lopcodes.h:
the 83 opcodes of Lua 5.4.7 in enum order (so `OpCode.ofNat?` is the C
`GET_OPCODE`), each with lopcodes.h's own one-line description.

    python3 scripts/gen_opcodes.py [--check]
"""
import os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
H = os.path.join(ROOT, "vendor/lua-5.4.7/src/lopcodes.h")
OUT = os.path.join(ROOT, "Lua/Bytecode/OpCode.lean")

def ops():
    src = open(H).read()
    body = src[src.index("typedef enum {"):src.index("} OpCode;")]
    res = []
    for line in body.splitlines():
        m = re.match(r"^(OP_[A-Z0-9]+),?\s*/\*\s*(.*?)\s*(\*/)?$", line)
        if m:
            doc = re.sub(r"\s+", " ", m.group(2).replace("*/", "")).strip().replace("-/", "- /")
            res.append((m.group(1)[3:], doc))
    assert len(res) == 83, len(res)
    return res

def render(os_):
    out = ["/-! GENERATED by scripts/gen_opcodes.py from vendor/lua-5.4.7/src/lopcodes.h",
           "-- do not edit. The 83 opcodes of Lua 5.4.7 in `enum OpCode` order. -/", "",
           "namespace Lua.Bytecode", "",
           "/-- Lua 5.4.7 opcodes; the constructor index is the 7-bit `OP` field. -/",
           "inductive OpCode where"]
    for n, d in os_:
        out.append(f"  /-- `{d}` -/")
        out.append(f"  | {n}")
    out.append("  deriving DecidableEq, Repr, Inhabited")
    out.append("")
    out.append("/-- All opcodes, in enum order. -/")
    out.append("def OpCode.all : List OpCode :=")
    out.append("  [" + ", ".join("." + n for n, _ in os_) + "]")
    out.append("")
    out.append("/-- `GET_OPCODE`: the opcode with number `n`, if `n < NUM_OPCODES`. -/")
    out.append("def OpCode.ofNat? (n : Nat) : Option OpCode := OpCode.all[n]?")
    out.append("")
    out.append("/-- The opcode's number (its index in `OpCode.all`). -/")
    out.append("def OpCode.toNat : OpCode → Nat")
    for i, (n, _) in enumerate(os_):
        out.append(f"  | .{n} => {i}")
    out.append("")
    out.append("theorem OpCode.all_length : OpCode.all.length = 83 := rfl")
    out.append("")
    out.append("theorem OpCode.ofNat?_toNat (o : OpCode) : OpCode.ofNat? o.toNat = some o := by")
    out.append("  cases o <;> rfl")
    out.append("")
    out.append("end Lua.Bytecode")
    out.append("")
    return "\n".join(out)

if __name__ == "__main__":
    t = render(ops())
    if "--check" in sys.argv:
        ok = os.path.exists(OUT) and open(OUT).read() == t
        print("opcodes: ok" if ok else "opcodes: DRIFT"); sys.exit(0 if ok else 1)
    open(OUT, "w").write(t); print("wrote", OUT)
