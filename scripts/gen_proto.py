#!/usr/bin/env python3
"""Undump a Lua 5.4 binary chunk (lundump.c's format) into a Lean `Proto`
literal, so the program the ELF embeds is a Lean term.

    python3 scripts/gen_proto.py c/tests/while.luac --name whileProto \
        -o Lua/Programs/While.lean [--check]

The chunk must be for the target's sizes (Instruction 4, lua_Integer 8,
lua_Number 8, little-endian): exactly what the host `luac` built from the
vendored source emits. The luac `-l -l` listing is embedded as a comment.
"""
import argparse, os, re, struct, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

class R:
    def __init__(s, b): s.b, s.i = b, 0
    def byte(s): v = s.b[s.i]; s.i += 1; return v
    def raw(s, n): v = s.b[s.i:s.i+n]; s.i += n; return v
    def unsigned(s):
        x = 0
        while True:
            c = s.byte(); x = (x << 7) | (c & 0x7f)
            if c & 0x80: return x
    def string(s):
        n = s.unsigned()
        return None if n == 0 else s.raw(n - 1)

def header(r):
    assert r.raw(4) == b"\x1bLua", "not a Lua chunk"
    assert r.byte() == 0x54 and r.byte() == 0, "not Lua 5.4 official format"
    assert r.raw(6) == b"\x19\x93\r\n\x1a\n"
    assert (r.byte(), r.byte(), r.byte()) == (4, 8, 8), "sizes"
    assert struct.unpack("<q", r.raw(8))[0] == 0x5678, "endianness/int"
    assert struct.unpack("<d", r.raw(8))[0] == 370.5, "float format"
    return r.byte()  # sizeupvalues of the main closure

def function(r):
    r.string(); r.unsigned(); r.unsigned()           # source, linedefined, lastline
    numparams, vararg, maxstack = r.byte(), r.byte(), r.byte()
    code = [struct.unpack("<I", r.raw(4))[0] for _ in range(r.unsigned())]
    k = []
    for _ in range(r.unsigned()):
        t = r.byte()
        if t == 0: k.append(".nil")
        elif t == 1: k.append(".bool false")
        elif t == 17: k.append(".bool true")
        elif t == 3: k.append(f".int {struct.unpack('<q', r.raw(8))[0] % 2**64}#64")
        elif t == 19: k.append(f".float 0x{struct.unpack('<Q', r.raw(8))[0]:016x}#64")
        elif t in (4, 20):
            s = r.string() or b""
            k.append(".str [" + ", ".join(str(c) for c in s) + "]")
        else: raise ValueError(f"constant tag {t}")
    ups = [(r.byte(), r.byte(), r.byte()) for _ in range(r.unsigned())]
    protos = [function(r) for _ in range(r.unsigned())]
    n = r.unsigned(); r.raw(n)                          # lineinfo
    for _ in range(r.unsigned()): r.unsigned(); r.unsigned()   # abslineinfo
    for _ in range(r.unsigned()): r.string(); r.unsigned(); r.unsigned()  # locvars
    for _ in range(r.unsigned()): r.string()            # upvalue names
    return (numparams, vararg, maxstack, code, k, ups, protos)

def lean(f, ind="  "):
    numparams, vararg, maxstack, code, k, ups, protos = f
    cs = ",\n".join(f"{ind}   0x{w:08x}#32" for w in code)
    ks = ", ".join(k)
    us = ", ".join(f"⟨{'true' if a else 'false'}, {b}, {c}⟩" for a, b, c in ups)
    ps = ", ".join(lean(p, ind + "  ") for p in protos)
    return (f".mk {numparams} {'true' if vararg else 'false'} {maxstack}\n{ind}  [\n{cs}]\n"
            f"{ind}  [{ks}]\n{ind}  [{us}]\n{ind}  [{ps}]")

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("chunk"); ap.add_argument("--name", required=True)
    ap.add_argument("-o", "--out", required=True); ap.add_argument("--check", action="store_true")
    ap.add_argument("--luac", default=os.path.join(ROOT, "c/luac"))
    a = ap.parse_args()
    data = open(a.chunk, "rb").read()
    r = R(data); header(r); f = function(r); assert r.i == len(data), "trailing bytes"
    listing = ""
    if os.path.exists(a.luac):
        listing = subprocess.run([a.luac, "-l", "-l", "-p", a.chunk], capture_output=True, text=True).stdout
        listing = listing.replace(a.chunk, os.path.basename(a.chunk)).replace("-/", "- /")
        listing = re.sub(r" (at|for) 0x[0-9a-f]+", "", listing).lstrip("\n")
    rel = os.path.relpath(a.chunk, ROOT)
    t = (f"import Lua.Bytecode.Syntax\n\n/-! GENERATED by scripts/gen_proto.py from `{rel}` -- do not edit.\n\n"
         f"```\n{listing}```\n-/\n\nnamespace Lua.Programs\n\nopen Lua.Bytecode\n\n"
         f"/-- The main function of `{rel}`. -/\ndef {a.name} : Proto :=\n  {lean(f)}\n\nend Lua.Programs\n")
    if a.check:
        ok = os.path.exists(a.out) and open(a.out).read() == t
        print(f"{a.out}: {'ok' if ok else 'DRIFT'}"); sys.exit(0 if ok else 1)
    os.makedirs(os.path.dirname(a.out), exist_ok=True); open(a.out, "w").write(t); print("wrote", a.out)

main()
