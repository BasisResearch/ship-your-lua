#!/usr/bin/env python3
"""Generate Lua/Vm/Image.lean: the immutable sections (.text, .rodata) of
c/lua-riscv-htif.elf as packed Lean data, the way ship-your-interpreter's
scripts/gen_fixed_image.py packs Vsa/Sim/Code/FixedImageData.lean
(256-byte pages as Nat literals, byte i of a page = bits 8i..8i+7, a
balanced if-tree over page numbers).

Because the embedded chunk lives in its own .lua_chunk section (link.ld),
these bytes are identical for every program; the ELF's sha256 is recorded.

    python3 scripts/gen_lua_image.py [--check]
"""
import hashlib, os, struct, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ELF = os.path.join(ROOT, "c/lua-riscv-htif.elf")
OUT = os.path.join(ROOT, "Lua/Vm/Image.lean")
PAGE = 256

def sections(raw):
    assert raw[:7] == b"\x7fELF\x02\x01\x01" and struct.unpack_from("<H", raw, 18)[0] == 243
    shoff = struct.unpack_from("<Q", raw, 40)[0]
    shentsize, shnum, shstrndx = struct.unpack_from("<HHH", raw, 58)
    hdr = lambda i: struct.unpack_from("<IIQQQQIIQQ", raw, shoff + i * shentsize)
    stroff = hdr(shstrndx)[4]
    out = {}
    for i in range(shnum):
        name, typ, flags, addr, off, size = hdr(i)[:6]
        n = raw[stroff + name: raw.index(b"\0", stroff + name)].decode()
        out[n] = (addr, raw[off:off + size] if typ != 8 else b"")
    return out

def tree(prefix, lo, hi):
    if hi - lo == 1: return f"{prefix}Page{lo}"
    mid = (lo + hi) // 2
    return f"(if page < {mid} then {tree(prefix, lo, mid)} else {tree(prefix, mid, hi)})"

def emit(prefix, base, data):
    lines = []
    npages = (len(data) + PAGE - 1) // PAGE
    for p in range(npages):
        chunk = data[p * PAGE:(p + 1) * PAGE]
        lines.append(f"private def {prefix}Page{p} : Nat := 0x{int.from_bytes(chunk, 'little'):x}")
    lines.append("")
    lines.append(f"private def {prefix}Page (page : Nat) : Nat :=\n  {tree(prefix, 0, npages)}")
    lines.append("")
    lines.append(f"/-- Byte `offset` of the section. -/")
    lines.append(f"def {prefix}Byte (offset : Nat) : BitVec 8 :=")
    lines.append(f"  BitVec.ofNat 8 (Nat.shiftRight ({prefix}Page (offset / {PAGE})) (8 * (offset % {PAGE})))")
    lines.append(f"def {prefix}Base : Nat := 0x{base:08x}")
    lines.append(f"def {prefix}Size : Nat := {len(data)}")
    lines.append("")
    return lines

def render():
    raw = open(ELF, "rb").read()
    sh = sections(raw)
    t_addr, text = sh[".text"]; r_addr, ro = sh[".rodata"]
    out = ["/-! GENERATED by scripts/gen_lua_image.py -- do not edit.",
           "",
           f"The immutable sections of `c/lua-riscv-htif.elf`",
           f"(sha256 `{hashlib.sha256(raw).hexdigest()}`):",
           f"`.text` at 0x{t_addr:08x} ({len(text)} bytes) and `.rodata` at 0x{r_addr:08x}",
           f"({len(ro)} bytes). Packed data only. -/", "",
           "namespace Lua.Vm.Image", ""]
    out += emit("text", t_addr, text)
    out += emit("rodata", r_addr, ro)
    out += ["/-- sha256 of the ELF these bytes were read from. -/",
            f"def elfSha256 : String := \"{hashlib.sha256(raw).hexdigest()}\"", "",
            "end Lua.Vm.Image", ""]
    return "\n".join(out)

if __name__ == "__main__":
    t = render()
    if "--check" in sys.argv:
        ok = os.path.exists(OUT) and open(OUT).read() == t
        print("image: ok" if ok else "image: DRIFT"); sys.exit(0 if ok else 1)
    open(OUT, "w").write(t); print("wrote", OUT, len(t), "bytes")
